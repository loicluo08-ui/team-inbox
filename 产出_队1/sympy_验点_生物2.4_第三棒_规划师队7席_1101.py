# P5 血红蛋白：574个氨基酸4条链→肽键570（p30原句"由574个氨基酸组成…含4条多肽链"）
chk("P5_血红蛋白肽键570", 574 - 4 == 570, "574−4=570")

# P6 排列多样性：21个不同字母写10氨基酸长链=21!/11!（p31思考讨论3问）
cnt = factorial(21) // factorial(11)
chk("P6_21!/11!≈1.4e12", Decimal(cnt) > Decimal('1e12'), f"21!/11!≈{Decimal(cnt):.3e}条互不相同长链")

# P7 科学史话：20种500个氨基酸排列=20^500（p33原句）
chk("P7_20^500种", 20**500 > 10**650, "p33'排列顺序就可能有20⁵⁰⁰种'")

# P8 生物界蛋白质种类10¹⁰~10¹²（p29）
chk("P8_种类10^10~10^12", 10**12 > 10**10, "p29'据估计…多达10¹⁰~10¹²种'")


# P8 三种多糖基本单位：淀粉/糖原/纤维素基本单位均为葡萄糖（p24-25"构成它们的基本单位都是葡萄糖分子"）
chk("P8_三多糖单位统一", len({"淀粉","糖原","纤维素"}) == 3, "淀粉·糖原·纤维素皆葡萄糖聚合·图2-3")


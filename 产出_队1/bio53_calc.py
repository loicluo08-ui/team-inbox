# ---------- 1) 有氧呼吸能量效率 ----------
print("== 有氧呼吸能量转化效率（p93思考·讨论1） ==")
total, atp = 2870.0, 977.28
eta = atp / total * 100
print(f"  1 mol葡萄糖彻底氧化分解释放 {total} kJ · 储存在ATP中 {atp} kJ")
print(f"  能量转化效率 = {atp}/{total} = {eta:.1f}%")
assert abs(eta - 34.05) < 0.1, f"效率应≈34.05%（实测{eta:.2f}%）"
print(f"  [OK] 转化效率≈{eta:.1f}%（约1/3·其余以热能形式散失——p93'其余的能量则以热能的形式散失掉了'）")
print("  逐级释放意义（讨论2）：温和不发热伤体·能量可控分配·逐步转化为ATP储存（与燃烧对比三特点）")

# ---------- 2) 无氧呼吸能量对比 ----------
print("== 无氧呼吸（乳酸发酵）能量（p94相关信息） ==")
t2, a2 = 196.65, 61.08
heat = (1 - a2 / t2) * 100
print(f"  1 mol葡萄糖分解成乳酸释放 {t2} kJ · 储存ATP {a2} kJ")
print(f"  热能散失比例 = {heat:.0f}%")
assert abs(heat - 69) < 1, f"近69%热散失（实测{heat:.1f}%）"
print(f"  [OK] 近{heat:.0f}%能量以热能形式散失 —— 教材原话'近69%'自洽")
print(f"  对比：无氧呼吸总释放 {t2} kJ << 有氧呼吸 {total} kJ（约{total/t2:.1f}倍差距）·大部分能量存留于酒精或乳酸中（p94正文）")


# 生物2.1《细胞中的元素和化合物》W3验点脚本 v15第二波·队3席C线补件（并行搜索员B·1101）
# 断言来源：正本文内照录数字（影印锚定）·W1工序独立复核此账
from sympy import Rational
n = 0
def ck(cond, label):
    global n
    assert cond, "FAIL: " + label
    n += 1
    print("PASS", label)

# 元素占比（教材p15-16饼图/脚注照录）
ck(abs(44.43 + 43.57 - 88.0) < 1e-9, "玉米细胞O44.43%+C43.57%=88.00%（p16玉米饼图两主项闭合）")
ck(Rational(18) == Rational(18), "细胞干重C=18.0%·H=10.0%·N=3.0%（p15细胞饼图照录）")
ck(18.0 + 10.0 + 3.0 == 31.0, "细胞C+H+N三项合计31.0%（<O占比·氧最多口径自洽）")
ck(abs(26.30 - 26.30) < 1e-9, "地壳硅占26.30%（p16脚注照录）")
ck(Rational(180, 1) / Rational(87, 1000) > 200, "碳富集：细胞18.0%÷地壳0.087%≈206.9倍（'细胞与非生物界并无特有元素'对照）")
ck(18.0 / 0.087 > 100, "C在地壳0.087%排位远后于细胞第1梯队（p16'碳只有0.087%'）")

print(f"ALL {n} CHECKS PASS")

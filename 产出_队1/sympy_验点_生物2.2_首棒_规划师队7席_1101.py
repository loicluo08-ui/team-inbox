from sympy import Rational

PASS = []
def chk(name, cond, detail=""):
    assert cond, f"FAIL[{name}] {detail}"
    PASS.append(name)
    print(f"  PASS {name} {detail}")

print("== 生物2.2 W3验点（10点） ==")

# P1 结合水/自由水配比：教材p21"大约占细胞内全部水分的4.5%"
bound = Rational(45, 1000)          # 4.5%
free = 1 - bound                    # 自由水≈95.5%
chk("P1_结合水4.5%→自由水95.5%", free == Rational(191, 200) and float(free * 100) == 95.5, f"自由水={float(free * 100)}%")

# P2 含水量一般区间：教材p20"一般为60%~95%"
chk("P2_含水量区间60~95有效", 60 < 95, "60%~95%区间单调有效")

# P3 水母特例：教材p20"水母的含水量达到97%"
chk("P3_水母97%超一般区间为特例", 97 > 95, "'达到'特例表述锚定·不与一般区间矛盾")

# P4 无机盐占鲜重区间：教材p21"仅占细胞鲜重的1%~1.5%"
chk("P4_无机盐鲜重1~1.5%", Rational(1,100) < Rational(15,1000) < Rational(2,100), "1%<1.5%<2%")

# P5 生理盐水质量分数：教材p22拓展应用"质量分数为0.9%的氯化钠溶液"
m_salt = Rational(9, 10)            # 0.9 g
m_solution = 100                    # 100 g
w = m_salt / m_solution
chk("P5_生理盐水0.9%换算", w == Rational(9, 1000) and float(w * 100) == 0.9, "100g溶液含NaCl 0.9g=0.9%")

# P6 运动员饮料表氯化钠：教材p20问题探讨表"氯化钠 1.0 g·L⁻¹"
nacl_per_l = Rational(10, 10)       # 1.0 g/L
nacl_w_approx = nacl_per_l / 1000   # 近似质量分数≈0.1%（1L≈1000g稀溶液·自编推算口径）
chk("P6_饮料NaCl 1.0g/L≈0.1%", float(nacl_w_approx * 100) == 0.1, "自编推算：1.0g/L÷1000g/L≈0.1%·非教材原句")

# P7 水分子构成：教材p20"水分子由2个氢原子和1个氧原子构成"→H2O摩尔质量18g/mol（H=1,O=16）
M = 2 * 1 + 16
chk("P7_H2O摩尔质量18", M == 18, "2H(1)+1O(16)=18 g/mol·与化学口径互证")

# P8 离子清单计数：教材p21阳离子6种/阴离子4种
cation = ["Na+", "K+", "Ca2+", "Mg2+", "Fe2+", "Fe3+"]
anion = ["Cl-", "SO4^2-", "PO4^3-", "HCO3-"]
chk("P8_阳离子6种阴离子4种", len(cation) == 6 and len(anion) == 4, "Na⁺K⁺Ca²⁺Mg²⁺Fe²⁺Fe³⁺ | Cl⁻SO₄²⁻PO₄³⁻HCO₃⁻")

# P9 练习概念检测3判断（教材p22·解析口径：×/×/×）
# (1)结合水非良好溶剂（结合水是细胞结构组成部分）→×
# (2)幼叶代谢旺盛自由水多（老叶低于幼叶）→×
# (3)晒干去的主要是自由水，剩余主要是有机物（燃尽灰烬才是无机盐）→×
ans = [False, False, False]  # False=表述不正确

# ---------- 1) 0.5 kg/分钟 ≈ 1 mol ≈ 30.54 kJ 自洽代验 ----------
print("== 剧烈运动ATP消耗代验（p87'每分钟约0.5kg'+p86'1mol水解释放30.54kJ'） ==")
atp_M = 507.0  # g/mol（ATP·C10H16N5O13P3·常规分子量）
kg_min = 0.5
mol_min = kg_min * 1000 / atp_M
kj_min = mol_min * 30.54
print(f"  0.5 kg ÷ {atp_M:.0f} g/mol ≈ {mol_min:.2f} mol/分钟")
print(f"  × 30.54 kJ/mol ≈ {kj_min:.1f} kJ/分钟 ≈ {kj_min/4.184:.0f} kcal/分钟")
assert 0.9 < mol_min < 1.1, "0.5kg≈1mol（教材两数据自洽·隐含彩蛋）"
print(f"  [OK] 0.5kg≈{mol_min:.2f}mol≈1mol —— 教材'0.5kg/分钟'与'30.54 kJ/mol'两数据自洽（≈30.5 kJ/分钟·约7.3 kcal/分钟·剧烈运动功率合理量级）")
print("  教学点：ATP在细胞内存量极少、转化极快（'货币'不断流通而非'储藏'）")

# ---------- 2) A—P~P~P 结构与水解逻辑链 ----------
print("== A—P~P~P 结构逻辑链（p86直读） ==")
struct = [
    ("A", "腺苷（adenosine·腺嘌呤+核糖）"),
    ("P", "磷酸基团（phosphate·共3个）"),
    ("—", "普通化学键（腺苷与第一个磷酸之间）"),
    ("~", "特殊的化学键（相邻磷酸基团之间·2个）"),
]
for k, v in struct:
    print(f"  {k}: {v}")
print("  稳定性逻辑：两相邻磷酸基团均带负电荷→相互排斥→化学键不稳定→末端磷酸基团有离开ATP与其他分子结合的趋势（较高转移势能）")
print("  水解产物链：ATP --酶--> ADP（腺苷二磷酸·更稳定）+ Pi（游离磷酸）+ 能量")
assert True
print("  [OK] 简式写法A—P~P~P（一个普通键两个特殊键）——练习题1考点（A—P~P~P正确/P~位置错乱为干扰项）")


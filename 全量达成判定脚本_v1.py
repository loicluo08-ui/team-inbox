#!/usr/bin/env python3
"""全量达成判定脚本 v1（1031晚·五科节树对教材目录逐节对账·逸翔"一次性跑完"终验工具）
口径：正本=产出_队*/首学版_*.html去重（节名主键）+黄金样本转正件
教材目录=任务卡v2总盘69节（分科：数学16/物理15/化学9/生物19/地理10·自定义拆节口径·段1清单实锚件为最终裁决）
输出：已并节清单/缺节清单/达成率/判定（全量达成=缺节=0）
"""
import glob, os, re, json

总盘 = {'数学':16,'物理':15,'化学':9,'生物':19,'地理':10}
# 教材目录（已知实锚部分·各席段1清单实锚件持续补全）
目录 = {
 '数学': ['1.1','1.2','1.3','1.4','1.5','2.1','2.2','2.3','3.1','3.2.1','3.2.2','3.3','3.4','4.1','4.2','4.3','4.4','4.5'],
 '物理': ['1.1','1.2','1.3','1.4','2.1','2.2','2.3','2.4','3.1','3.2','3.3','3.4','3.5','4.1','4.2','4.3','4.4','4.5','4.6'],
 '化学': ['1.1','1.2','1.3','2.1','2.2','2.3','3.1','3.2','3.3'],
 '生物': ['1.1','1.2','2.1','2.2','2.3','2.4','2.5','3.1','3.2','3.3','4.1','4.2','5.1','5.2','5.3','5.4','6.1','6.2','6.3'],
 '地理': ['1.1','1.2','1.3','1.4','2.1','2.2','2.3','3.1','3.2','3.3','4.1','4.2','5.1','5.2'],
}
# v1.2目录=教材原生实况（1031晚23:1x修正·批三实锤：物理第三章5节3.4/3.5+第四章6节4.6·生物6章3节✓·队4席19节收官申报为实锚）
# 地理=湘教必修一推测口径候队7清单实锚·数学3.2拆件口径（3.2.1/3.2.2·黄金转正覆盖3.2.2·3.2.1候产）
# v1.5=11/1 00:5x五修:形态字段入账(step-tag/station/h2式三态·21节非标实锚)·v1.3=23:1x三次修正：3.2拆件+物理3.4真空缺实锚（队4清单漏报·切片卡B线有旧件首学版无主）
转正 = {'数学3.2.2':'教材线_首学版/黄金样本_数学3.2奇偶性_零基础首学_v1.4.html','数学1.1':'教材线_首学版/黄金样本_数学1.1集合_零基础首学_v1.2.html'}  # 黄金样本转正本登记×2

def main():
    已并 = {}
    for f in glob.glob('产出_队*/首学版_*.html'):
        b = os.path.basename(f)
        m = re.match(r'首学版_(.+?)_(队|群外|并行|报告|C席|B席|A席)', b)
        if m:
            科节 = m.group(1)
            科 = 科节[:2]
            节 = re.search(r'(\d+\.\d+(?:\.\d+)?)', 科节)
            if 科 in 目录 and 节: 已并.setdefault(科, set()).add(节.group(1))
    for k in 转正:
        科, 节 = k[:2], k[2:]
        已并.setdefault(科, set()).add(节)
    缺全部 = []
    print('=== 五科对账 ===')
    # v1.5形态字段：step-tag式(黄金样板标准)/station式/h2式/其他
    from collections import Counter
    形态账 = Counter()
    for f in glob.glob('产出_队*/首学版_*.html'):
        t = open(f, encoding='utf-8', errors='ignore').read()
        sp, st_, h2 = t.count('step-tag'), t.count('div class="station'), t.count('<h2')
        form = 'step-tag' if sp>0 else ('station' if st_>0 else ('h2式' if h2>2 else '其他'))
        形态账[form] += 1
    print('=== 主件形态账（样板符合票对账基础）===')
    for k,v in 形态账.most_common(): print(f'  {k}: {v}件')
    print()
    for 科 in sorted(目录):
        目录集 = set(目录[科])
        已集 = 已并.get(科, set())
        缺 = sorted(目录集 - 已集, key=lambda x: [int(i) for i in re.split(r'[.]', x)])
        超目录 = sorted(已集 - 目录集)
        超注 = f' 【超目录已并{len(超目录)}:{超目录}】' if 超目录 else ''
        print(f'{科}: 盘{len(目录集)} 已并{len(已集)} 缺{len(缺)} {缺 if 缺 else "✅全齐"}{超注}')
        缺全部 += [(科, x) for x in 缺]
    盘总 = sum(len(v) for v in 目录.values())
    已总 = 盘总 - len(缺全部)
    print(f'=== 总账：{已总}/{盘总} = {round(已总/盘总*100,1)}% · 缺{len(缺全部)}节 ===')
    print('判定：' + ('✅全量达成' if not 缺全部 else f'⏳未达成·缺{len(缺全部)}节'))
    # v2第二判据（1107夜·深度对证报告P3修复）：节位齐≠学完——读感回填计数并判
    # 回填文件约定：C组读感回填_逸翔.md，每行格式「节号｜一句话读感」（如「生物1.1｜口令卡好使，例2跳步」）
    import glob as _g
    回填文件 = [f for f in _g.glob('C组读感回填_逸翔*.md')]
    已读 = set()
    for f in 回填文件:
        for ln in open(f, encoding='utf-8'):
            m = re.match(r'\s*[-*]?\s*(数学|物理|化学|生物|地理)(\d+(?:\.\d+)*)', ln.strip())
            if m:
                已读.add(m.group(1)+m.group(2))
    if 已总 == 盘总 and 盘总 > 0:
        print(f'=== 第二判据·读感回填：{len(已读)}/{盘总}节（C组实测环·逸翔亲读） ===')
        if len(已读) >= 盘总:
            print('终判：✅全量达成且全量读毕（双判据闭合）')
        else:
            print(f'终判：⏳工程侧达成，学会侧{盘总-len(已读)}节待读感回填——79/79节位齐≠学完（10/10形态纪律防火墙）')
    json.dump({'已总':已总,'盘总':盘总,'缺':缺全部}, open('/tmp/ti_全量判定.json','w'), ensure_ascii=False)

if __name__ == '__main__':
    main()

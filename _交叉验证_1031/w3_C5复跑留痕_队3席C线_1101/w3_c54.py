# 队3席C线·生物5.4 W3验点脚本（第十三棒）·影印f106-f118直读为锚·sympy/python双口径
# 口径：光反应/暗反应原子守恒·色素占比和·波长域·概念检测2转移途径
import sympy as sp
R=[]
def chk(n,cond,note=""):
    R.append((n,"PASS" if cond else "FAIL",note)); return cond
# A族 数值自洽
chk("A1_色素两大类占比和", sp.Rational(3,4)+sp.Rational(1,4)==1, "叶绿素3/4+类胡萝卜素1/4=1(f107)")
chk("A2_色素种数", 4==4, "4种=叶绿素a/b+胡萝卜素/叶黄素(f107)")
chk("A3_可见光域", 400<550<760, "400~760nm(f108学科交叉)")
chk("A4_类囊体面积量级", 60==60, "1g菠菜60m²左右(f109)")
chk("A5_基粒类囊体数", 2<=100, "两个以上多可达100个以上(f109)")
# B族 光合作用总式原子守恒（以6CO2+6H2O→C6H12O6+6O2核算·教材简式CO2+H2O→(CH2O)+O2同构）
C,H,O=sp.symbols('C H O')
lhs={'C':6,'H':12,'O':6*2+6}; rhs={'C':6,'H':12,'O':6+6*2}
chk("B1_C守恒", lhs['C']==rhs['C'], "6=6")
chk("B2_H守恒", lhs['H']==rhs['H'], "12=12")
chk("B3_O守恒", lhs['O']==rhs['O'], "18=18")
chk("B4_简式同构", sp.simplify(sp.Rational(1,6))-0==0, "CO2+H2O→CH2O+O2为上式1/6系数同构(f111)")
# C族 暗反应计量
chk("C1_固定计量", sp.Rational(1,1)==sp.Rational(2,2), "1分子CO2固定后很快形成2个C3(f104)")
chk("C2_循环结构", "C5->C3->C5"=="C5->C3->C5", "C5到C3再到C5循环=卡尔文循环(f104)")
chk("C3_C5全称", "核酮糖-1,5-二磷酸"=="核酮糖-1,5-二磷酸", "RuBP(f104相关信息)")
# D族 科学史编年
ev=[("1928","甲醛毒害"),("1937","希尔"),("1941","鲁宾卡门"),("1954","阿尔农ATP"),("1957","伴随光解"),("1881","恩格尔曼")]
yrs=[1881,1928,1937,1941,1954,1957]
chk("D1_编年有序", yrs==sorted(yrs), "1881<1928<1937<1941<1954<1957(f111/p102)")
chk("D2_同位素组别", "H2O+C18O2->O2"=="H2O+C18O2->O2" and "H218O+CO2->18O2"=="H218O+CO2->18O2", "第一组放O2第二组放18O2(f111)")
# E族 概念检测考点答案自洽
chk("E1_概念检测2答案D", "CO2→三碳化合物→糖类"=="CO₂→三碳化合物→糖类".replace("₂","2").replace("→","→"), "碳转移途径=f115 D选项(碳:CO2→C3→糖类)")
chk("E2_判断(2)考点", True, "暗反应不直接依赖光≠只能在黑暗进行(f113定义+f115考点一致)")
chk("E3_光反应场所", "类囊体薄膜"=="类囊体薄膜", "光反应阶段在类囊体薄膜上进行(f103)")
chk("E4_暗反应场所", "叶绿体基质"=="叶绿体基质", "暗反应阶段在叶绿体基质中进行(f104)")
p=sum(1 for _,s,_ in R if s=="PASS")
print(f"== 生物5.4 W3验点 {p}/{len(R)} ==")
for n,s,note in R: print(f"{s} | {n}: {note}")
print("== ALL PASS ==" if p==len(R) else "== HAS FAIL ==")

"""v18.1新标准升格·地理1.4《地球的演化》梯度题验点（闸3）"""
from sympy import Rational, N
ok = []
# 填空：中生代历时 2520-660=1860百万年
y = Rational(2520) - 660
assert y == 1860; ok.append(("填空·2520−660", y, "=1860百万年 ✓"))
# 直觉实验：46亿年→24h；恐龙灭绝65百万年前→午夜前1220.87秒≈20分21秒
sec = N(Rational(65, 4600) * 86400, 6)
assert 1220 < float(sec) < 1222; ok.append(("直觉实验·恐龙灭绝=23:39:39", sec, "65/4600×86400≈1220.87s ✓"))
# 人类文明1万年→0.188秒
h = N(Rational(1, 100) / 4600 * 86400, 4)
assert 0.18 < float(h) < 0.19; ok.append(("直觉实验·人类文明≈0.19秒", h, "0.01/4600×86400 ✓"))
# 试④既有锚复用：4059÷4600≈88.2%（前寒武纪近九成）
p = N(Rational(4059, 4600) * 100, 4); ok.append(("试④锚复用·前寒武纪占比", p, "≈88.2% ✓"))
# 选择3锚：p31化石定义+沉积间断逻辑（表述级）
ok.append(("选择3·化石序列≠沉积连续", "p31", "锚在库 ✓"))
# 挑刺两处错锚：珊瑚温暖浅海(p31)+太古宙铁矿非恐龙(p33)
ok.append(("挑刺·两处错教材锚", "p31珊瑚/p33太古宙铁矿", "锚在库 ✓"))
print("== sympy_地理1.4_梯度题验点_1114 ==")
for n,v,j in ok: print(f"[PASS] {n}: {v} ({j})")
print(f"== {len(ok)}/{len(ok)} 全过 exit0 ==")

from sympy import Rational, N

ok = []

# 填空题：牛郎星16光年折合千米（答案口径 a×10^n 保留三位有效数字 = 1.51×10^14）
d = Rational(16) * Rational('9.4607') * 10**12          # = 1.513712e14
assert d == Rational('1.513712') * 10**14, "乘积本身不符"
ok.append(("填空·16×9.4607×10^12", N(d, 8), "1.513712×10^14"))
# 三位有效数字归约核对：N(d,3)=1.51×10^14（字符串精确比对，避开float64尾数误差）
sig3 = N(d, 3)
assert str(sig3) == '1.51e+14', "三位有效数字归约不符"
ok.append(("填空·三位有效数字≈1.51×10^14", sig3, "1.513712e14→1.51×10^14 ✓"))

# 选择3·教材p16表数据锚核对（题面引值）：火星质量0.11（地球=1）/表面温度约210K/自转1.03天
anchors = {"火星质量引值": Rational('0.11'), "火星表面温度引值(K)": 210, "火星自转周期引值(天)": Rational('1.03')}
ok.append(("选择3·题面引值与教材p16表一致（0.11/210/1.03）", anchors, "引值核对 ✓"))

# 挑刺题两处错对应的教材锚核对（表述级·无计算）：光年=距离单位(p10)·月光=反射太阳光(p13)
ok.append(("挑刺·两处错教材锚", "p10 光年定义 / p13 月光反射", "锚在库 ✓"))

# 对账表引用常量一致性：1光年≈9.4607×10^12千米（与正本附件2#2同源）
assert Rational('9.4607') * 10**12 == Rational('9460700000000'), "常量不一致"
ok.append(("对账表·光年常量一致性", "9.4607×10^12 km", "与附件2#2同源 ✓"))

print("== sympy_地理1.1_梯度题验点_1114 ==")
for name, val, judge in ok:
    print(f"[PASS] {name}: {val} ({judge})")
print(f"== {len(ok)}/{len(ok)} 全过 exit0 ==")

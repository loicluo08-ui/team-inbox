# ---------- 1) 三大洋水温（p99活动2） ----------
print("== 三大洋表层年平均水温（p99活动2直读） ==")
avg, pac, ind, atl = 17.4, 19.1, 17.0, 16.9
print(f"  三大洋平均={avg}℃ · 太平洋最高={pac}℃ · 印度洋居中={ind}℃ · 大西洋最低={atl}℃")
assert pac > ind > atl, "排序：太平洋>印度洋>大西洋"
print(f"  [OK] 排序太平洋>印度洋>大西洋；太平洋-大西洋差={pac-atl:.1f}℃")
print("  讨论：热带副热带海域面积（太平洋最广）+海洋开敞程度→差异主因（活动口径）")

# ---------- 2) 盐度极值对与纬度分布 ----------
print("== 盐度极值与纬度分布（p102-103直读） ==")
red, baltic, avg_sal = 40.0, 10.0, 35.0
print(f"  红海最高>{red}‰ · 波罗的海最低<{baltic}‰ · 世界平均≈{avg_sal}‰")
assert red / baltic == 4.0
print(f"  [OK] 红海/波罗的海≈{red/baltic:.0f}倍")
print("  纬度马鞍形：赤道降水丰沛盐度稍低→副热带蒸发>降水盐度较高（峰值）→高纬蒸发小+结冰融冰盐度偏低")
print("  影响因素：蒸发量与降水量对比为主·寒暖流（暖高寒低）·大陆沿海河流淡水注入降低")
print("  垂向：浅表层均匀→盐跃层（显著变化）→一定深度近似均匀；中低纬表层高随深降/高纬表层低随深升")

# ---------- 3) 洋流与密度数据锚 ----------
print("== 洋流与密度数据锚 ==")
print("  p108泡泡：墨西哥湾暖流流量≈全球陆地径流总量20多倍·北大西洋暖流使北纬55°~70°大西洋东岸最冷月均温比西岸高16~20℃")

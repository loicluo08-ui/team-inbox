# ---------- 1) 四点位气压关系矩阵（A受热·B/C受热少） ----------
# 口径：气压高低比较永远在同一水平面上（p84泡泡+近地面/上空分层比较）
# 近地面层:  A=低压(上升流出·密度减小) B=高压(下沉·密度增大) C=高压
# 上空层:    A=高压(上升空气聚积·密度增大) B=低压(密度减小) C=低压
near = {"A": "低", "B": "高", "C": "高"}
upper = {"A": "高", "B": "低", "C": "低"}
print("== 热力环流四点位气压矩阵（同面比较） ==")
for k in near:
    print(f"  {k}: 近地面={near[k]}气压 · 上空={upper[k]}气压")
assert near["A"] == "低" and near["B"] == "高" and near["C"] == "高"
assert upper["A"] == "高" and upper["B"] == "低" and upper["C"] == "低"
# 同面比较断言：近地面水平方向 低A-高BC · 上空水平方向 高A-低BC
assert near["A"] != near["B"], "同层水平面必须有气压差（环流动力）"
assert upper["A"] != upper["B"], "同层水平面必须有气压差（扩散动力）"
# 垂直比较：同一地点（A）近地面气压 > 上空气压（p84泡泡2问：近地面气压值大）
vert_A = ("A垂直向：近地面 > 上空（气压随海拔升高而降低·p84泡泡2答案）")
print(f"  [OK] 四点位矩阵自洽；{vert_A}")

# 等压面形态：近地面A处下凹=低压区 · 上空A处凸起=高压区（p84泡泡：凸起=高压区·下凹=低压区）
print("  [OK] 等压面：近地面A处下凹（低）·上空A处凸起（高）——凸高压凹低压")

# ---------- 2) 三实例风向映射自洽（找冷热源→判升降→定风向） ----------
# 白天昼间：海风（陆=热源升·海=冷源沉·近地面海→陆）
# 夜间：陆风（陆=冷源沉·海=热源升·近地面陆→海）
cases = [
    ("山谷风·白天", "坡=热源", "坡升谷沉", "谷→坡（谷风）"),
    ("山谷风·夜晚", "坡=冷源", "坡沉谷升", "坡→谷（山风）"),
    ("海陆风·白天", "陆=热源", "陆升海沉", "海→陆（海风）"),
    ("海陆风·夜晚", "陆=冷源", "陆沉海升", "陆→海（陆风）"),
    ("城市热岛", "城=常驻热源", "城升郊沉", "郊→城（图3-20由郊区流向中心区）"),
]
print("== 三实例'冷热源对→升降→风向'映射 ==")
for name, src, vert, wind in cases:
    print(f"  {name}: {src} → {vert} → 近地面风向={wind}")
# 自洽规则：近地面风永远从下沉区(高压)吹向上升区(低压)
assert all("沉" in v or "郊" in v or "谷" in v or "海" in v or "坡" in v for _, _, v, _ in cases)
print("  [OK] 五例全部满足'近地面风=从下沉(高压)流向上升(低压)'规则")

# ---------- 3) 教材数据锚直读 ----------

# ---------- 1) 水体家族数据链 ----------
print("== 地球水体数据链（p89直读） ==")
d1, d2, d3 = 1384, 273, 56  # 三个水珠直径km（全部水/液态淡水/河流湖泊淡水）
print(f"  探究三水珠：①全部水={d1}km ②液态淡水(沼泽河流湖泊地下水)={d2}km ③河流湖泊淡水={d3}km")
assert d1 > d2 > d3
ocean, land = 0.97, 0.03
print(f"  海洋水≈全球水储量{ocean*100:.0f}% · 陆地各种水体不足{land*100:.0f}%")
assert abs(ocean + land - 1.0) < 1e-9
print("  冰川=地球淡水主体·占全球淡水储量2/3以上（两极+中低纬高山）")
print("  人类利用较多淡水（河水+淡水湖泊水+浅层地下水）≈全球淡水储量0.3%")
assert 0.003 < 2/3, "人类可用占比远小于冰川主体"
print("  [OK] 数据链自洽：97%+3%=100% · 1384>273>56 · 0.3%<<2/3")

# ---------- 2) 黄河输沙造陆（p94阅读直读） ----------
print("== 黄河输沙造陆数据链 ==")
s_total, s_bed = 16, 4  # 亿吨/年
s_sea = s_total - s_bed
print(f"  年输沙16亿吨 → 4亿吨淤积下游河床 · 其余{s_sea}亿吨输入渤海造黄河三角洲")
assert s_sea == 12
area_total, area_yr = 1100, 39  # 平方千米（1954-1982总/年均）
years = 1982 - 1954
print(f"  1954—1982共{years}年·造陆{area_total}平方千米·年均约{area_yr}平方千米·海岸线年均外延470米")
assert area_total / years >= area_yr - 1, f"总造陆/年数≈{area_total/years:.1f}≈年均39吻合"
print(f"  [OK] 年均核验：{area_total}/{years}={area_total/years:.1f}≈39（教材口径'约'相容）")
print("  1999年以来退耕还林（草）·黄土高原植被覆盖率31.6%→约65%·土壤侵蚀强度大幅下降·年入黄河泥沙量显著减少")

# ---------- 3) 三类型循环自洽 + 轮换周期 ----------
print("== 水循环三类型（p92直读·逻辑自洽） ==")
cycles = {
    "海陆间循环（大循环）": "海洋蒸发→水汽输送→陆地降水→径流（地表+地下）→回海·地表水主要循环方式·陆地水持续补充水资源再生",
    "陆地内循环": "大陆上水汽→凝结降水仍落大陆·补给陆地水体水量较少",
    "海上内循环": "海洋蒸发→海洋上空凝结降水→落回海面",
}
for k, v in cycles.items():
    print(f"  {k}: {v}")
# 外流区同时参与海陆间+陆地内循环（p92泡泡：在外流区存在水的陆地内循环吗——存在）
print("  [OK] 外流区陆地内循环存在（p92泡泡自答口径·显式标注）")
print("  p93泡泡：大气水汽平均每8天多轮换一次·全球河水平均每16天多轮换一次")
assert 8 < 16
print("  [OK] 周期锚：大气8天 < 河水16天（直读）")
print("\n[ALL OK] geo41_calc.py 三组代验通过")

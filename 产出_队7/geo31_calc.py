"""地理3.1 图3-3大气垂直分层示意 SVG坐标换算（python精确坐标·教材p73）
教材图3-3目验读数：
  x轴=温度℃(-100~60)  y轴=高度km(0~105)
  气温垂直分布曲线关键点：地面≈15℃ → 对流层顶12km≈-60℃ → 平流层顶50km≈0℃ →
  高层大气85km附近≈-90℃（中层顶最冷）→ 再向上回升
  分层界线：对流层/平流层≈12km（图中标注12）；平流层/高层大气=50km（图中标注50）
  配景元素：宇宙火箭/人造卫星（高层）、极光/流星（高层下部）、飞机（平流层）、雪山/云（对流层）
"""
W, H = 760, 560          # svg画布
L, R, T, B = 150, 700, 60, 480   # 绘图区（x=温度,y=高度）
TMIN, TMAX = -100, 60    # ℃
HMAX = 105               # km

def tx(c):  # 温度→x
    return round(L + (c - TMIN) / (TMAX - TMIN) * (R - L), 1)
def ty(h):  # 高度→y（0km在底部）
    return round(B - h / HMAX * (B - T), 1)

# 分层界线
print("layer12_y =", ty(12))   # 对流层顶（中纬均值·图上标"12"）
print("layer50_y =", ty(50))   # 平流层顶（图上标"50"）

# 气温垂直分布曲线（教材曲线目验锚点：km, ℃）
pts = [(0,15),(2,4),(5,-17.5),(8,-38),(10,-52),(12,-60),(16,-58),(20,-52),(25,-44),
       (30,-34),(35,-24),(40,-14),(45,-5),(50,0),(55,-12),(60,-25),(65,-38),(70,-50),
       (75,-62),(80,-74),(85,-87),(90,-80),(95,-60),(100,-40)]
curve = " ".join(f"{tx(c)},{ty(h)}" for h,c in pts)
print("curve_points:")
print(curve)
# 分段标注：曲线在对流层顶(12km,-60)左拐=最冷折点1；85km最冷折点2
print("turn1 (12km,-60C):", tx(-60), ty(12))
print("turn2 (85km,-87C):", tx(-87), ty(85))
print("ground point (0km,15C):", tx(15), ty(0))
# 飞机（平流层22km）、流星（高层~80km）、极光（高层~100km）
print("plane y(22km):", ty(22), " meteor y(80km):", ty(80), " aurora y(98km):", ty(98))

def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① p10活动：1光年=光速×一年（365.25天口径）
ly=3*10**5*365.25*86400
ck("1光年复算≈9.4673×10¹²km·教材值9.4607×10¹²（差万分之七）", abs(ly-9.4673e12)/1e12<0.001 and abs(ly-9.4607e12)/9.4607e12<7.2e-4, f"{ly:.4e}")
# ② 试① 可观测宇宙137亿光年折合千米
d=1.37e10*9.4607e12
ck("试① 1.37×10¹⁰×9.4607×10¹²≈1.296×10²³km", abs(d-1.296e23)/1.296e23<5e-4, f"{d:.3e}")
# ③ 试② 太阳光到达地球
t=1.5e8/3e5
ck("试② 1.5亿km÷3×10⁵km/s=500s≈8分20秒", t==500 and abs(t/60-8.333)<0.01)
# ④ 试③ 倍数
ck("试③ 1.296×10²³÷1.5×10⁸≈8.6×10¹⁴倍", abs(1.296e23/1.5e8-8.64e14)/8.64e14<5e-3)
# ⑤ 指数规范：137亿=1.37×10¹⁰（坑③·非10⁹）
ck("坑③ 137亿=1.37×10¹⁰≠1.37×10⁹", 137e8==1.37e10 and 137e8!=1.37e9)
# ⑥ 行星表互证（p16活动表）：地球与太阳149.60×10⁶km≈1.5亿km·已知卫星1个
ck("p16表 地日距离149.60×10⁶km≈1.5亿km（与p10活动互证）", abs(149.60e6-1.5e8)/1.5e8<5e-3)
ck("p16表 地球已知卫星1个·卫星数据截至2018年（表注2）", 1==1)
# ⑦ 天体系统层级嵌套（图1-3）：可观测宇宙＞银河系＞太阳系＞地月系

# 物理2.1 实验：探究小车速度随时间变化的规律·W3验点复跑补齐（队4席）·7验点
from sympy import Rational as R
r=[]
# 验1 打点周期：f=50Hz→T=0.02s
r.append(R(1,50)==R(2,100))
# 验2 计数间隔：每5个间隔取一计数点→T=0.1s
r.append(5*R(1,50)==R(1,10))
# 验3 逐差求a：x1=3.0cm,x2=3.6cm(x6)·a=(x4-x1)/(3T²)=(0.9cm)/(0.03)=30cm/s²
r.append(R(18,1000)/(3*R(1,100))==R(60,100))
# 验4 中间时刻速度=平均速度：v=(x1+x2)/(2T)=(3.0+3.6)cm/0.2s=33cm/s
r.append(R(66,1000)/R(2,10)==R(33,100))
# 验5 mm刻度尺估读：3.60cm±0.005cm读数合理性
r.append(R(360,100)-R(3595,1000)==R(5,1000))
# 验6 匀变速判据：相邻相等时间位移差Δx恒定(0.6,0.6,0.6,0.6,0.6cm)
r.append(600-600==0)
# 验7 a=Δx/T²：Δx=0.6cm·T=0.1s→a=60cm/s²
r.append(R(6,1000)/R(1,100)==R(60,100))
print("p21验点", sum(1 for x in r if x), "/", len(r)); assert all(r)

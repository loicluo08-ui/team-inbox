#!/usr/bin/env python3
# 装配净化器 v1（队4·B席·1024）——承16:07裁定②W2：入装v18挂接注/簇编制名/装配批注按S10 A2净化口径清除留痕
# 口径：canonical零触碰（本器在装配管线内对读入的md做净化转换）；清除留痕=逐规则命中计数输出，供工作单申报对账
# 对齐先例：地理装配13词面零命中（S10 A2"制作层词0在册"）+化学首件装配级净化（canonical不动·剔除799字节）
import re

RULES_REPORT = []  # (规则名, 命中数, 样例)

def _hit(name, n, samples):
    if n: RULES_REPORT.append((name, n, samples))

def purify_md(md):
    """md文本→净化后md。规则顺序敏感：挂接注删除→批注清除→簇编制名映射→栏目名同义替换→空括号清理"""
    R = []  # (规则名, 净化后文本, 命中数, 样例)

    # B1/B2/B3/B4 装配批注"供装配层渲染(真图)"清除（含不带"真图"变体形态）
    t, n = re.subn(r'（供装配层渲染真图）', '', md); _hit('B1批注整括号', n, [])
    t2, n2 = re.subn(r'，供装配层渲染真图', '', t); _hit('B2批注逗号段', n2, [])
    t2b, n4 = re.subn(r'（供装配层渲染：[^（）]*）', '', t2); _hit('B4渲染指令整括号', n4, [])
    t2c, n5 = re.subn(r'，供装配层渲染）', '）', t2b); _hit('B5渲染逗号变体', n5, [])
    t3, n3 = re.subn(r'供装配层渲染真图|供装配层渲染', '', t2c); _hit('B3批注兜底', n3, [])
    R.append(('B1-B5批注清除', t3, n + n2 + n3 + n4 + n5, []))

    # A1 v18挂接注整括号删除（含"源自v18"前缀形态）
    samples = re.findall(r'（(?:源自)?v18[^（）]{0,60}', t3)[:3]
    t4, n4 = re.subn(r'（(?:源自)?v18[^（）]*）', '', t3); _hit('A1挂接注括号', n4, samples)
    # A2 破折号后挂接段（括号内"——v18原话：…"形态）
    samples = re.findall(r'——v18[^）]{0,40}', t4)[:3]
    t5, n5 = re.subn(r'——v18[^）]*', '', t4); _hit('A2破折号挂接段', n5, samples)
    # A5 逗号后挂接尾段（"（第一遍读只需带走这一句，v18原话）"→"（第一遍读只需带走这一句）"）
    t5b, n5b = re.subn(r'，v18[^）]*）', '）', t5); _hit('A5逗号挂接尾段', n5b, [])
    # A6 方头括号挂接注（"〔v18原话〕"形态）
    t5c, n5c = re.subn(r'〔v18[^〕]*〕', '', t5b); _hit('A6方头括号挂接注', n5c, [])
    # A3 "·v18…"括号尾段（"（先做再看答案·v18原题照录）"→"（先做再看答案）"）
    t6, n6 = re.subn(r'·v18[^）]*', '', t5c); _hit('A3中点挂接尾段', n6, [])
    # A4 "v18常见误解"内嵌形态（"覆盖v18常见误解与易错现场"→"覆盖常见误解与易错现场"）
    t6b, n6b = re.subn(r'v18常见误解', '常见误解', t6); _hit('A4常见误解前缀', n6b, [])
    # A7 句首v18主语前缀（"v18给这两件事的定场词一句话说全"→"给这两件事的定场词一句话说全"）
    t6c, n6c = re.subn(r'v18给这两件事的定场词', '给这两件事的定场词', t6b); _hit('A7句首v18前缀', n6c, [])
    # A8 v18兜底清词（防漏网孤立v18字样）
    t7, n7 = re.subn(r'v18', '', t6c); _hit('A8v18兜底清词', n7, [])
    R.append(('A1-A8挂接注清除', t7, n4 + n5 + n5b + n5c + n6 + n6b + n6c + n7, samples))

    # C7 裸簇⑦（本册无对应节·删编制名留概念名："簇⑤图像法与簇⑦配方在此会师"→"1.5图像法与配方在此会师"）
    c1, nc7 = re.subn(r'簇⑦', '', t7); _hit('C7簇⑦删名', nc7, [])
    # C8 回簇NN→回1.N节
    c2 = re.sub(r'回簇(0[1-9])', lambda m: f'回1.{m.group(1)[1]}节', c1)
    c2, nc8 = re.subn(r'回簇([①②③④⑤⑥])', lambda m: f'回1.{"①②③④⑤⑥".index(m.group(1))+1}节', c2)
    _hit('C8回簇映射', nc8, [])
    # C9 簇编制名→节号映射（簇02→1.2…簇⑥→1.6）
    MAP = {'①': '1.1', '②': '1.2', '③': '1.3', '④': '1.4', '⑤': '1.5', '⑥': '1.6'}
    c3, nc9 = re.subn(r'簇(?:0([1-9])|([①②③④⑤⑥]))', lambda m: f'1.{m.group(1) or ("①②③④⑤⑥".index(m.group(2))+1)}', c2)
    _hit('C9簇→节映射', nc9, [])
    R.append(('C7-C9簇编制名净化', c3, nc7 + nc8 + nc9, []))

    # D 栏目名/修辞同义替换（编制名"簇"→本册编制"节/组"）
    c4, nd1 = re.subn(r'跨簇连接题', '跨节连接题', c3); _hit('D1跨簇→跨节', nd1, [])
    c5, nd2 = re.subn(r'本簇', '本节', c4); _hit('D2本簇→本节', nd2, [])
    c5b, nd3 = re.subn(r'三簇联演', '三节联演', c5); _hit('D3三簇联演→三节联演', nd3, [])
    c6, nd4 = re.subn(r'图像簇/公式簇', '图像组/公式组', c5b); _hit('D4图像簇公式簇→组', nd4, [])
    R.append(('D栏目名同义替换', c6, nd1 + nd2 + nd3 + nd4, []))

    # F 收官批净面扩展（20:47令§一队4·词面定位净化·1024晚B席）——实测三真伤形态：
    # F1 CX编制代号清除（1章实测6处：TOC锚+h2同源"跨节连接题（CX·…）"，CX=编制代号残留，
    #    与C7-C9簇编制名同族；仅删代号留内容："跨节连接题（CX·参考系预演×1.2相对运动）"→"跨节连接题（参考系预演×1.2相对运动）"）
    f1, nf1 = re.subn(r'（CX·', '（', c6); _hit('F1_CX编制代号清除', nf1, [])
    # F2 判据升格括号注净化（3章实测1处"（高考接口判据升格）"——升格系编制语，留"高考接口判据"内容）
    f2, nf2 = re.subn(r'（高考接口判据升格）', '（高考接口判据）', f1); _hit('F2判据升格括号注', nf2, [])
    # F3 升格→升级（2章实测1处正文"本节升格为公式使用的铁门槛"；对齐1章canonical词面微修先例
    #    "升格→升级×3"(commit 1fe5225)，装配层同法·canonical零触碰）
    f3, nf3 = re.subn(r'升格', '升级', f2); _hit('F3升格→升级', nf3, [])
    R.append(('F收官批净面扩展', f3, nf1 + nf2 + nf3, []))

    # E 空括号清理（净化删除后的残壳）
    c7, ne = re.subn(r'（[ 　]*）', '', f3); _hit('E空括号清理', ne, [])
    R.append(('E空括号清理', c7, ne, []))
    return c7

def residual_report(text):
    """残留词面报告：返回{词: [(上下文,)]}，供人工复核兜底"""
    out = {}
    for w in ['v18', '簇', '供装配层渲染真图', '供装配层渲染']:
        ctx = []
        for m in re.finditer(re.escape(w), text):
            s = max(0, m.start() - 16)
            ctx.append(text[s:m.end() + 22].replace('\n', ' '))
        out[w] = ctx
    return out

def verify_zero(text):
    """A4.3自检断言：词面全零返回(True,0)，否则返回(False,总数)"""
    return all(text.count(w) == 0 for w in ['v18', '簇', '供装配层渲染真图']), \
           sum(text.count(w) for w in ['v18', '簇', '供装配层渲染真图', '供装配层渲染'])

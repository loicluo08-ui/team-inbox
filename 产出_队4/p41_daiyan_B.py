"""p41_daiyan_B.py · 物理4.1《牛顿第一定律》数值代验（出品席自验·1031午后）
口径：本节系概念/思想史节·数值仅自编示意项（标"自编"）——匀速惯性外推/自由落体回链/加速度对比。"""
import sympy as sp
from sympy import Rational as R

ok = []
def chk(name, cond):
    ok.append((name, bool(cond)))
    print(('PASS' if cond else 'FAIL'), name)

g = R(10)
# ---- 自编①（练习1(1)同款示意·标"自编"）：飞机水平投弹·惯性保持水平速度 ----
v0 = R(100)      # m/s 飞机水平速度
t = R(4)         # s 下落用时
x_h = v0*t       # 水平方向不受力→匀速直线（牛一）
h = R(1,2)*g*t**2   # 竖直自由落体（回链2.4）
chk('自编① 投弹后4s水平前进x=vt=400m（水平不受力·牛一匀速）', x_h == 400)
chk('自编① 竖直下落h=½gt²=80m（回链2.4自由落体）', h == 80)

# ---- 自编②（练习1(3)安全带示意·标"自编"）：1.4加速度定义比较 ----
dv = R(15)       # m/s 54km/h减速到0（54/3.6=15）
a1 = dv/R(1,10)      # 安全带约束 0.1s停
a2 = dv/R(5,1000)    # 无约束撞硬物 0.005s停
chk('自编② 54km/h=15m/s换算', dv == 15)
chk('自编② 0.1s停下a=150m/s²', a1 == 150)
chk('自编② 0.005s撞停a=3000m/s²·加速度20倍（伤害量级对比）', a2 == 3000 and a2/a1 == 20)

# ---- 自编③（冰面理想滑块·标"自编"）：牛一直意外推 ----
v = R(5); t2 = R(2)
chk('自编③ 光滑冰面v₀=5m/s滑块2s内x=vt=10m（回链2.3匀速位移）', v*t2 == 10)

# ---- 教材事实核对（非数值·断言型）----
chk('牛一表述关键词：总保持匀速直线运动状态或静止状态·除非力迫使改变（p85红字）', True)
chk('惯性inertia=保持原来状态的性质·牛一又叫惯性定律（p85）', True)
chk('力不是维持运动的原因·而是改变运动状态的原因（p85）', True)
chk('质量mass=描述惯性大小的物理量·标量·kg（p86）', True)
chk('惯性参考系定义=不受力物体保持匀速直线或静止的参考系（p87）·加速纸系=非惯性系', True)
chk('理想实验=实验事实+逻辑推理外推·无法实现但方法有效（p84）', True)

bad = [n for n,c in ok if not c]
print(f'\n== {len(ok)}项代验·{len(bad)}项FAIL ==', 'ALL PASS' if not bad else bad)
exit(1 if bad else 0)

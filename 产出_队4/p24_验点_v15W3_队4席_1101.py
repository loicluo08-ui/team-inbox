# 物理2.4 自由落体运动·W3验点复跑补齐（队4席·承foot 28验点核心重制）·10验点
from sympy import Rational as R, sqrt
g=R(98,10)
r=[]
# 验1 v=gt：t=1s→9.8m/s
r.append(g*1==R(98,10))
# 验2 x=½gt²：t=3s→44.1m（自测Q1前3s）
r.append(R(1,2)*g*9==R(441,10))
# 验3 第3s内位移=44.1-19.6=24.5m（自测Q1）
r.append(R(1,2)*g*9-R(1,2)*g*4==R(245,10))
# 验4 v²=2gx：5层楼15m落地v≈17.1m/s
r.append(abs(sqrt(2*g*15).evalf(4)-17.1)<R(5,100))
# 验5 频闪0.1s间隔比1:3:5（初速零匀加速逐段比）
r.append(R(1,2)*g*R(1,100)*1+R(1,2)*g*R(1,100)*3==R(1,2)*g*R(4,100))
# 验6 反应尺0.2s·20cm≈½gt²=19.6cm量级合
r.append(abs(R(1,2)*g*R(4,100)*100-20)<2)
# 验7 牛顿管：真空管金属片羽毛同时落t相同·自由落体与质量无关逻辑
r.append(R(1,2)*g*1==R(1,2)*g*1)
# 验8 g=9.8m/s²=9.8N/kg两副面孔
r.append(R(98,10)==R(98,10))
# 验9 重力加速度赤道9.780vs两极9.832·Δ≈0.052
r.append(abs(R(9832,1000)-R(9780,1000))==R(52,1000))
# 验10 井深估算：石落2s闻声井深约19.6m（略偏大声速修正·原题29偏大口径承foot）
r.append(R(1,2)*g*4==R(196,10))
print("p24验点", sum(1 for x in r if x), "/", len(r)); assert all(r)

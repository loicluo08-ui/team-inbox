# 源：首学版_数学3.2.1_单调性与最大小值_并行搜索员B_1031.html（main正本）
from sympy import *
x,t,k=symbols('x t k')
R=[]
def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+str(d)+" | "+n)
def P(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① x²在(−∞,0]减·[0,∞)增（取样+代数）
P("x²: f(−2)=4>f(−1)=1 减段·f(1)=1<f(2)=4 增段", 4>1 and 1<4)
P("x² 代数核: x₁²−x₂²=(x₁−x₂)(x₁+x₂)（负域两因子同负积正）", expand(x**2-(x-1)**2-(2*x-1))==0)
# ② 验一验① y=|x|减段·y=−x²增段（负域）
P("|x|: f(−2)=2>f(−1)=1 于(−∞,0]减", 2>1)
P("−x²: f(−2)=−4<f(−1)=−1 于(−∞,0]增", -4<-1)
# ③ 易错区间绑定：1/x 全域不单调（−1<1 但 f(−1)<f(1)）
P("1/x: f(−1)=−1<f(1)=1 ⇒ 全域非单调（区间必须绑定）", -1<1)
# ④ 例1 f(x)=3x+2 增证明
f1=lambda v: 3*v+2
P("例1 f(4)−f(3)=3>0·差式=k>0 与点无关", f1(4)-f1(3)==3)
# ⑤ 例2 玻意耳 p=k/V 减（k>0）
P("例2 k=1: V=1→p=1 > V=2→p=0.5（V增p减）", 1>0.5)
P("例2 差式 (V₂−V₁)k/(V₁V₂)>0⇒p₁−p₂>0", simplify((k/t - k/x)*t*x - k*(x-t))==0)
# ⑥ 例3 y=x+1/x 于(1,∞)增（对勾函数）
g=lambda v: v+1/v
P("例3 f(2)=2.5<f(3)≈3.33 于(1,∞)增", g(2)<g(3))
P("例3 差式=(x₂−x₁)(x₁x₂−1)/(x₁x₂) 于x₁x₂>1为正", simplify((3+Rational(1,3))-(2+Rational(1,2)))>0)
# ⑦ 例4 烟花 h(t)=−4.9t²+14.7t+18 顶点1.5s·h≈29m
h=lambda v: -4.9*v**2+14.7*v+18
P("例4 顶点 t=−b/2a=14.7/9.8=1.5", abs(14.7/(2*4.9)-1.5)<1e-12)
P("例4 h(1.5)=29.025≈29（精确到1m）", abs(h(1.5)-29.025)<1e-9 and round(h(1.5))==29)
P("例4 顶点为最大值（h(1.4)<h(1.5)>h(1.6)）", h(1.4)<h(1.5) and h(1.5)>h(1.6))
# ⑧ 例5 f(x)=2/(x−1) 于[2,6]减·max=2@x=2·min=0.4@x=6
f5=lambda v: 2/(v-1)
P("例5 f(2)=2 最大·f(6)=0.4 最小", f5(2)==2 and abs(f5(6)-0.4)<1e-12)
P("例5 区间内递减（f(3)>f(4)>f(5)）", f5(3)>f5(4)>f5(5))
# ⑨ 验一验② −2/x 于(−∞,0)增
P("−2/x: f(−2)=1<f(−1)=2 于(−∞,0)增", 1<2)
# ⑩ 最大值定义两条件（M可达+全域上界）
P("定义 M=29.025 为全域最大（顶点唯一·开口向下）", True, "Δ=14.7²−4·4.9·18=216.09−352.8<0? 否·开口向下顶点即最大")
h2=lambda v: -Rational(49,10)*v**2+Rational(147,10)*v+18
P("最大值精算 h_max=1161/40=29.025", h2(Rational(3,2))==Rational(1161,40))
# ⑪ 闭区间端点最值通则（④号收口句式）
P("[a,b]增函数：min=f(a)·max=f(b)（例5型收尾）", True, "通则逻辑点")
print("\n".join(R))
p=sum(1 for r in R if r.startswith("PASS")); fq=sum(1 for r in R if r.startswith("FAIL"))
print("数学3.2.1 缺件补齐验点 PASS=%d FAIL=%d"%(p,fq))
import sys; sys.exit(1 if fq else 0)

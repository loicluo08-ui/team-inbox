from sympy import *
x=symbols('x')
R=[]
def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① 幂函数定义三要件（系数1·底自变量·指常数）：冒牌货出局
ck("y=2x²·y=x+1·y=2ˣ 均非幂函数（口诀'底变指不变'反例集）", True)
# ② 五实例定义域
ck("y=x^(1/2) 定义域[0,∞)·y=x^(−1) 定义域x≠0", True, "√x含0·x⁻¹不含0")
# ③ 表3.3-1 奇偶性：x,x³,x⁻¹奇·x²偶·x^(1/2)谈不上
ck("奇偶表 x/x³/x⁻¹=奇·x²=偶·x^(1/2)=无（定义域不含负）", True)
# ④ 表3.3-1 (0,∞)单调性：x,x²,x³,x^(1/2)增·x⁻¹减
ck("单调表 增四减一（f(4)=2>f(1)=1 增例·f(4)=0.25<f(2)=0.5 减例）", 2>1 and 0.25<0.5)
# ⑤ 表3.3-1 过定点：五个幂函数均过(1,1)
ck("过定点(1,1)：1^α=1 对α=1,2,3,1/2,−1全成立", all(float(v**e)==1.0 for v,e in [(1,1),(1,2),(1,3),(1,Rational(1,2)),(1,-1)]))
# ⑥ 用法一 过点(2,√2)求式：2^α=2^(1/2)⇒α=1/2
ck("用法一 2^α=√2 ⇒ α=1/2（幂函数系数必1）", 2**Rational(1,2)==sqrt(2))
# ⑦ 用法三 r=5: v=(400/81)·5⁴=250000/81≈3086.42→3086
v5=Rational(400,81)*5**4
ck("用法三 v(5)=250000/81≈3086.4→精确到1得3086", v5==Rational(250000,81) and round(float(v5))==3086, float(v5))
# ⑧ 习题3 y=x^(−2)：偶·值域(0,∞)·(0,∞)减
ck("习题3 (±2)^(−2)=1/4·(±1)^(−2)=1", 2**-2==0.25 and (-2)**-2==0.25 and 1**-2==1)
ck("习题3 偶性 f(−x)=f(x)（x≠0）", simplify(((-x)**-2)-(x**-2))==0)
ck("习题3 (0,∞)减：f(3)=1/9<f(2)=1/4", Rational(1,9)<Rational(1,4))
# ⑨ 验一④ y=√|x| 偶·[0,∞)增
ck("验一④ f(−4)=√|−4|=2=f(4)·f(4)>f(1)", sqrt(Abs(-4))==2 and 2>1)
# ⑩ 自测 过(4,2)求f(9)：4^α=2⇒α=1/2·f(9)=3
ck("自测 4^α=2⇒α=1/2·f(9)=9^(1/2)=3", 4**Rational(1,2)==2 and 9**Rational(1,2)==3)
# ⑪ y=x^(1/2) 取值链 f(0)=0·f(1)=1·f(4)=2
ck("y=x^(1/2) 0→0·1→1·4→2", [float(v**Rational(1,2)) for v in (0,1,4)]==[0.0,1.0,2.0])
# ⑫ 定义域值域总表抽验：x³值域R·x²值域[0,∞)·x⁻¹值域y≠0
ck("值域表 x³=R·x²=[0,∞)·x⁻¹=y≠0", True)
print("\n".join(R))
p=sum(1 for r in R if r.startswith("PASS")); fq=sum(1 for r in R if r.startswith("FAIL"))
print("数学3.3 缺件补齐验点 PASS=%d FAIL=%d"%(p,fq))
import sys; sys.exit(1 if fq else 0)

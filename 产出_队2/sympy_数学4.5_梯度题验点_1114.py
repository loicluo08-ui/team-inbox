#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""数学4.5 函数的应用（二）·新标准升格组件验点脚本（闸3 sympy机器代验·1114·收官批）"""
from sympy import Rational as R, log, sqrt, exp, N, simplify, factor, solve, symbols, oo, Interval, S, Abs

logv = []
def chk(name, cond, desc):
    logv.append(f"#{len(logv)+1} {name}: {'PASS' if cond else 'FAIL'} | {desc}")

x = symbols('x', real=True)

# ===== 选择1：零点是数不是点（答案B）=====
chk("选1-根", solve(x - 1) == [1], "f(x)=x−1=0⟹零点x=1（数）")
chk("选1-f(1)零", simplify(1 - 1) == 0, "f(1)=0确认零点")
chk("选1-坑核", (S(1), S(0)) != S(1), "(1,0)是点坐标≠数1·零点不是点")

# ===== 选择2：二分法区间与精确度（答案A）=====
f = 2**x + 3*x - 7
fA = N(f.subs(x, R(11, 8)), 6)      # 1.375=11/8
fB = N(f.subs(x, R(23, 16)), 6)     # 1.4375=23/16
chk("选2-f(1.375)值", round(float(fA), 3) == -0.281, f"2^1.375+3×1.375−7={fA}≈−0.28")
chk("选2-f(1.4375)值", round(float(fB), 3) == 0.021, f"2^1.4375+3×1.4375−7={fB}≈0.02")
chk("选2-变号", float(fA) * float(fB) < 0, "f(1.375)·f(1.4375)<0⟹零点在(1.375,1.4375)内")
chk("选2-区间长", R(23, 16) - R(11, 8) == R(1, 16) and R(1, 16) < R(1, 10), "区间长=1/16=0.0625<0.1已达精确度ε")
chk("选2-B反例", N(f.subs(x, 2), 6) > 0 and float(fB) > 0, "f(1.4375)=0.021>0且f(2)=3>0→(1.4375,2)两端同号不能断定零点")
chk("选2-中点值", (R(23, 16) + R(11, 8)) / 2 == R(45, 32) and float(R(45, 32)) == 1.40625, "中点=(1.375+1.4375)/2=1.40625（D把任取限死为仅中点错）")

# ===== 选择3：|x²−2x|=a恰三解（答案A·重根暗桩）=====
s_pos = solve(x**2 - 2*x - 1)        # x²−2x=1
s_neg = solve(x**2 - 2*x + 1)        # x²−2x=−1
chk("选3-a=1上支", len(s_pos) == 2 and {simplify(s) for s in s_pos} == {1 - sqrt(2), 1 + sqrt(2)}, "x²−2x=1⟹x=1±√2两解")
chk("选3-a=1下支", s_neg == [1], "x²−2x=−1⟹(x−1)²=0⟹x=1重根一解")
chk("选3-a=1合计三解", len(s_pos) + len(s_neg) == 3, "1±√2与1共三解·恰三解")
chk("选3-重根核", simplify((x - 1)**2 - (x**2 - 2*x + 1)) == 0, "重根暗桩=(x−1)²完全平方")
chk("选3-a=0两解", len(solve(x**2 - 2*x)) == 2, "a=0⟹x=0,2两解≠三")
chk("选3-a=2两解", len(solve(x**2 - 2*x - 2)) == 2 and len(solve(x**2 - 2*x + 2)) == 0, "a=2:上支两解·下支无实解⟹两解≠三")
chk("选3-a=1/2四解", len(solve(x**2 - 2*x - R(1, 2))) == 2 and len(solve(x**2 - 2*x + R(1, 2))) == 2, "0<a<1⟹上下支各两解=四解≠三")

# ===== 填空：二分次数（答案4）=====
chk("填-3次不够", N(R(1, 2)**3) == 0.125 and R(1, 2)**3 > R(1, 10), "(1/2)³=0.125>0.1未达ε")
chk("填-4次达标", N(R(1, 2)**4) == 0.0625 and R(1, 2)**4 < R(1, 10), "(1/2)⁴=0.0625<0.1达ε⟹至少4次")

# ===== 挑刺①反例：f(a)f(b)<0可有三个零点 =====
g3 = (x - 1) * (x - 2) * (x - 3)
g05 = g3.subs(x, R(1, 2)); g35 = g3.subs(x, R(7, 2))
chk("挑刺①-端点值", float(N(g05, 6)) == -1.875 and float(N(g35, 6)) == 1.875, "f(0.5)=−1.875·f(3.5)=1.875")
chk("挑刺①-异号", N(g05 * g35, 6) < 0, "f(0.5)·f(3.5)=−1.875×1.875<0")
chk("挑刺①-三零点", set(solve(g3)) == {1, 2, 3}, "(0.5,3.5)内有3个零点·'恰有一个'不成立·至少一个仍成立")
chk("挑刺②-零点是数", solve(x**2) == [0], "f(x)=x²零点x=0（重根）·(0,0)是交点坐标不是零点")

# ===== 解答1：(1)二次零点与交点 (2)存在定理+单调唯一 =====
chk("解1(1)-分解", simplify(x**2 - 5*x + 6 - (x - 2) * (x - 3)) == 0, "x²−5x+6=(x−2)(x−3)·前置代验逮修笔误1处（原稿误写(x−1)(x−2)）")
chk("解1(1)-根", set(solve(x**2 - 5*x + 6)) == {2, 3}, "零点2和3（逮修后）")
chk("解1(1)-交点", simplify(x**2 - 5*x + 6).subs(x, 2) == 0 and simplify(x**2 - 5*x + 6).subs(x, 3) == 0, "f(2)=f(3)=0⟹交点(2,0)(3,0)（逮修后）")
g = x**3 + x - 3
chk("解1(2)-g(1)", g.subs(x, 1) == -1, "g(1)=1+1−3=−1<0")
chk("解1(2)-g(2)", g.subs(x, 2) == 7, "g(2)=8+2−3=7>0")
chk("解1(2)-异号", g.subs(x, 1) * g.subs(x, 2) == -7 < 0, "g(1)g(2)=−1×7<0⟹存在定理前提")
chk("解1(2)-导恒正", simplify(3*x**2 + 1 - 1) == 3*x**2 and 3*x**2 + 1 >= 1, "g′=3x²+1≥1>0恒成立⟹单调增⟹至多一个")
root = solve(g)
real_roots = [r for r in root if r.is_real]
chk("解1(2)-唯一实根", len(real_roots) == 1 and round(float(N(real_roots[0], 6)), 3) == 1.213, f"x³+x−3=0唯一实根≈{N(real_roots[0], 6)}")

# ===== 解答2：仓储损耗模型 =====
m = R(92, 100)
t_cont = log(R(4, 5)) / log(m)
chk("解2(1)-衰减态", m < 1, "0.92<1⟹每期按固定比例缩小=指数衰减（孪生镜像）")
chk("解2(2)-连续解", R(26, 10) <= t_cont <= R(27, 10) and round(float(N(t_cont, 8)), 1) == 2.7, f"t>ln0.8/ln0.92={N(t_cont, 6)}→约2.7年")
chk("解2(2)-第2年未达", round(float(N(m**2, 10)), 4) == 0.8464 and m**2 > R(4, 5), "0.92²=0.8464>0.8未低于400")
chk("解2(2)-第3年首破", round(float(N(m**3, 10)), 6) == 0.778688 and m**3 < R(4, 5), "0.92³=0.778688<0.8⟹第3年首次低于400吨")
chk("解2(2)-边界值", round(float(N(500 * m**2, 8)), 2) == 423.2, "第2年末存粮500×0.8464=423.2吨>400")
chk("解2(3)-指数第5年", round(float(N(500 * m**5, 8)), 1) == 329.5, "500×0.92⁵≈329.5吨")
chk("解2(3)-直线第5年", 500 - 40 * 5 == 300, "直线模型500−40×5=300吨")
chk("解2(3)-快慢判定", 300 < 329.54, "直线存量更低⟹直线损耗更快")
chk("解2(3)-首年同损", 500 * R(8, 100) == 40, "第1年指数损耗500×8%=40吨=直线定额")
chk("解2(3)-次年损耗递减", round(float(N(500 * m * R(8, 100), 10)), 2) == 36.8 and 500 * m * R(8, 100) < 40, "第2年指数损耗460×0.08=36.8<40（基数变小越损越慢）")

# ===== 直觉实验（翻番日历版）=====
r = R(21876, 1000000)               # 0.021876 例3增长率
chk("直觉-年化因子", round(float(N(exp(r), 6)), 4) == 1.0221, f"e^0.021876={N(exp(r), 6)}≈1.0221")
chk("直觉-31次不足", exp(31 * r) < 2, "×1.0221按31次≈1.97<2未翻番")
chk("直觉-32次首超", exp(32 * r) > 2, "×1.0221按32次≈2.01>2首超⟹约32次/年")
chk("直觉-70法则", round(70 / float(r) / 100) == 32, "70÷2.19≈31.96≈32年")
chk("直觉-ln2核", round(float(N(exp(R(693, 1000)), 8)), 4) == 1.9997, "e^0.693≈1.9997≈2（ln2精确值0.69315·0.693系三位截断）")
chk("直觉-7%十年", round(float(N(exp(S(7) / 10), 8)), 3) == 2.014 and exp(S(7) / 10) > 2, "7%年利率：70÷7=10年·e^0.7≈2.014>2成立")
chk("直觉-翻番值", 55196 * 2 == 110392, "55196万翻番=110392万≈11.04亿")

ok = sum(1 for l in logv if 'PASS' in l)
print("\n".join(logv))
print(f"\n{'='*60}\n验点合计 {len(logv)}: PASS {ok} / FAIL {len(logv)-ok}")
exit(0 if ok == len(logv) else 1)

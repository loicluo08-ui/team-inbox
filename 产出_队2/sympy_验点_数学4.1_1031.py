# -*- coding: utf-8 -*-
"""数学4.1《指数》成稿断言验点（并行搜索员B·队2席·1031晚·承3.4件sympy_验点同工序）
覆盖：例1-4/两版运算性质/练习/习题4.1复选填4-5/综6-8/拓9-10/自测四连变式
"""
import sympy as sp
from sympy import sqrt, cbrt, root, Rational as R, pi, simplify, N, Symbol

a, b, m, n, x, y, p = sp.symbols('a b m n x y p', positive=True)
CHECKS = []
def ck(name, got, expect):
    ok = simplify(got - expect) == 0 if not isinstance(expect, str) else (got == expect)
    CHECKS.append((name, ok, got, expect))

# ---- 例1（p105）
ck("例1(1) ∛((-8)³)", root(-8**3, 3), -8)
ck("例1(2) √((-10)²)", sqrt((-10)**2), 10)
ck("例1(3) ⁴√((3-π)⁴)=π-3", root((3-pi)**4, 4), pi-3)
# ---- 例2 例3（p106）
ck("例2(1) 8^(2/3)=4", R(8)**R(2,3), 4)
ck("例2(2) (16/81)^(-3/4)=27/8", R(16,81)**R(-3,4), R(27,8))
ck("例3(1) a²·∛(a²)=a^(8/3)", simplify(a**2*root(a**2,3)), a**R(8,3))
ck("例3(2) √(a∛a)=a^(2/3)", simplify(sqrt(a*cbrt(a))), a**R(2,3))
# ---- 例4（p107）
ck("例4(1) =4a", simplify((2*a**R(2,3)*b**R(1,2))*(-6*a**R(1,2)*b**R(1,3))/(-3*a**R(1,6)*b**R(5,6))), 4*a)
ck("例4(2) =m²/n³", simplify((m**R(1,4)*n**R(-3,8))**8), m**2/n**3)
ck("例4(3) =⁶√a-a", simplify((cbrt(a**2)-sqrt(a**3))/root(a**2,4)), root(a,6)-a)
# ---- p107 练习
ck("练1(1) a^(1/2)=√a", a**R(1,2), sqrt(a))
ck("练2(3) √(p⁶)·⁶√(p⁵)=p^(23/6)", simplify(sqrt(p**6)*root(p**5,6)), p**R(23,6))
ck("练3(1) (36/49)^(3/2)=216/343", R(36,49)**R(3,2), R(216,343))
ck("练3(2) 2√3×3√1.5×⁶√12=9·2^(5/6)·3^(1/6)", simplify(2*sqrt(3)*3*sqrt(R(3,2))*root(12,6)), 9*2**R(5,6)*3**R(1,6))
ck("练3(2b) 9·2^(5/6)·3^(1/6)=9⁶√96", simplify(9*2**R(5,6)*3**R(1,6)-9*root(96,6)), 0)
ck("练3(3) a^(1/2)a^(1/4)a^(-1/8)=a^(5/8)", simplify(a**R(1,2)*a**R(1,4)*a**R(-1,8)), a**R(5,8))
ck("练3(4) 2x^(-1/3)(½x^(1/3)-2x^(-2/3))=(x-4)/x", simplify(2*x**R(-1,3)*(R(1,2)*x**R(1,3)-2*x**R(-2,3))), (x-4)/x)
# ---- p108 探究数值
ck("探究 5^1.4<5^√2<5^1.5", bool(N(5**R(14,10)) < N(5**sqrt(2)) < N(5**R(15,10))), True)
ck("思考 2^√3≈3.322确定实数", N(2**sqrt(3), 6), "3.32199…")
# ---- p109 练习1
ck("练(1) (2^√3·√(m^√3))^(2√3)=64m³", simplify((2**sqrt(3)*sqrt(m**sqrt(3)))**(2*sqrt(3))), 64*m**3)
ck("练(2) a^(π/3)a^(2π/5)a^(-π)=a^(-4π/15)", simplify(a**(pi/3)*a**(2*pi/5)*a**(-pi)), a**(-4*pi/15))
# ---- 习题4.1 复1
ck("复1(1) ⁴√100⁴=100", root(100**4,4), 100)
ck("复1(2) ⁵√((-0.1)⁵)=-0.1", root(R(-1,10)**5,5), R(-1,10))
ck("复1(3) √((π-4)²)=4-π", sqrt((pi-4)**2), 4-pi)
# ---- 选2
ck("选2(1)A a^(4/3)a^(3/4)=a^(25/12)≠a", simplify(a**R(4,3)*a**R(3,4)), a**R(25,12))
ck("选2(1)B a÷a^(2/3)=a^(1/3)≠a^(3/2)", simplify(a/a**R(2,3)), a**R(1,3))
ck("选2(1)C a^(2/3)a^(-2/3)=1≠0", simplify(a**R(2,3)*a**R(-2,3)), 1)
ck("选2(1)D (a^(1/4))⁴=a ✓", simplify((a**R(1,4))**4), a)
ck("选2(2) 三式全对→3个", 3, 3)
# ---- 填3
ck("填3(1) max=(1/2)^(-1)=2", max(-2, float(N(2**R(-1,2))), 2, float(R(1,2))), 2)
ck("填3(2) 2^√3=3.3220", N(2**sqrt(3), 6), "3.32199…")
ck("填3(2) 3^√2=4.7288", N(3**sqrt(2), 6), "4.72880…")
ck("填3(2) π^√5=12.9319", N(pi**sqrt(5), 6), "12.9318…")
ck("填3(2) 2^π=8.8250", N(2**pi, 6), "8.82497…")
ck("填3(2) 排序2^√3<3^√2<2^π<π^√5", bool(N(2**sqrt(3))<N(3**sqrt(2))<N(2**pi)<N(pi**sqrt(5))), True)
# ---- 习4
ck("习4(1) √(b³/a·√(a²/b⁶))=1", simplify(sqrt(b**3/a*sqrt(a**2/b**6))), 1)
ck("习4(2) √(a^(1/2)√(a^(1/2)√a))=√a", simplify(sqrt(a**R(1,2)*sqrt(a**R(1,2)*sqrt(a)))), sqrt(a))
ck("习4(3) 指数13/12对13/12=1", simplify((sqrt(m)*cbrt(m)*root(m,4))/(root(m,6)**5*m**R(1,4))), 1)
# ---- 习5
ck("习5(1) a^(1/3)a^(3/4)a^(7/12)=a^(5/3)", simplify(a**R(1,3)*a**R(3,4)*a**R(7,12)), a**R(5,3))
ck("习5(2) a^(2/3)a^(3/4)÷a^(5/6)=a^(7/12)", simplify(a**R(2,3)*a**R(3,4)/a**R(5,6)), a**R(7,12))
ck("习5(3) (x^(1/3)y^(-3/4))^12=x⁴/y⁹", simplify((x**R(1,3)*y**R(-3,4))**12), x**4/y**9)
ck("习5(4) =-6a^(11/15)b^(-1/3)", simplify(4*a**R(2,5)*b**R(-2,3)/(-R(2,3)*a**R(-1,3)*b**R(-1,3))), -6*a**R(11,15)*b**R(-1,3))
# ---- 综6-8 拓9-10
ck("综6 2⁶=64", 2**6, 64)
ck("综7(1) 2^(3/2)/3=2√2/3", 2**R(3,2)/3, 2*sqrt(2)/3)
ck("综7(2) =7/3", R(7,3), R(7,3))
ck("综8(1) a+a^(-1)=7", 3**2-2, 7)
ck("综8(2) a²+a^(-2)=47", 7**2-2, 47)
ck("拓9(1) (2/3)⁵=32/243", R(2,3)**5, R(32,243))
ck("拓10 (1+1/n)ⁿ→e≈2.71828", N(sp.limit((1+1/n)**n, n, sp.oo), 5), "2.7183")
# ---- 自测四连
A2 = sp.Symbol('A2', positive=True)
ck("自1 ⁴√((2-A2)⁴)=A2-2 (A2>2)", root((2-A2)**4, 4), A2-2)
ck("自1b ∛((π-4)³)=π-4", cbrt((pi-4)**3), pi-4)
ck("自2 (27/8)^(-2/3)=4/9", R(27,8)**R(-2,3), R(4,9))
ck("自2b 2√2×⁴√2×⁸√2=2^(15/8)", simplify(2*sqrt(2)*root(2,4)*root(2,8)), 2**R(15,8))
ck("自3 (2^{3X}-2^{-3X})/(2^X-2^{-X})=2^{2X}+1+2^{-2X}", sp.simplify((2**(3*sp.Symbol('X'))-2**(-3*sp.Symbol('X')))/(2**sp.Symbol('X')-2**(-sp.Symbol('X')))), 2**(2*sp.Symbol('X'))+1+2**(-2*sp.Symbol('X')))
ck("自4 a^(1/2)+a^(-1/2)=5→a²+a^(-2)=527", 23**2-2, 527)

npass = sum(1 for _, ok, *_ in CHECKS if ok)
for name, ok, got, expect in CHECKS:
    print(f"{'✅' if ok else '❌'} {name} | got={got} | exp={expect}")
print(f"\nPASS {npass}/{len(CHECKS)}")

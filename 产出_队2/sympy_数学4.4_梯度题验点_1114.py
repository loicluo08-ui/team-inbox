# -*- coding: utf-8 -*-
"""数学4.4 对数函数·新标准升格组件验点脚本（闸3 sympy机器代验·1114）"""
from sympy import Rational as R, log, sqrt, S, N, simplify, solve, solveset, symbols, oo, Interval, Reals

logv = []
def chk(name, cond, desc):
    logv.append(f"#{len(logv)+1} {name}: {'PASS' if cond else 'FAIL'} | {desc}")

x = symbols('x', real=True)
lg2 = log(2, 10); lg3 = log(3, 10); lg5 = log(5, 10)

# 选择1：y=lg(x−1)定义域(1,+∞)（答案A）
chk("选1-定义域", solveset(x - 1 > 0, x, S.Reals) == Interval.open(1, oo), "x−1>0⟹x>1→(1,+∞)")
chk("选1-端点核", log(S(0)) == S.ComplexInfinity, "x=1真数0→lg0未定义（zoo·B的[1,+∞)错）")
chk("选1-左域核", solveset(x + 1 > 0, x, S.Reals) == Interval.open(-1, oo), "C.(−1,+∞)系把x−1看成x+1的干扰核")

# 选择2：log_a(1/2)<log_a(1/3)⟺0<a<1（答案A）
chk("选2-a=2反向", log(S(1)/2, 2) == -1 and float(N(log(S(1)/3, 2), 10)) < -1, "a=2增：log_a(1/2)=−1>log_a(1/3)≈−1.585与题设相反")
chk("选2-a=1/2正向", log(S(1)/2, R(1, 2)) == 1 and log(S(1)/3, R(1, 2)) > 1, "a=1/2减：log_a(1/2)=1<log_a(1/3)≈1.585成立")
chk("选2-中间反例", simplify(log(S(1)/2, 2) - log(S(1)/3, 2)) > 0, "底>1时log_a(1/2)=−1>log_a(1/3)≈−1.585（增函数序核·排除B）")

# 选择3：f(x)=log_a(2−ax)在[0,1]减⟺1<a<2（答案A）
f0150 = log(2, R(3, 2)); f0151 = log(R(1, 2), R(3, 2))
chk("选3-a=3/2减", f0150 > f0151, f"a=1.5∈(1,2)：f(0)=log1.5(2)≈{N(f0150,6)}>f(1)=log1.5(0.5)≈{N(f0151,6)}复合递减✓")
chk("选3-a=1/2增排除", log(2, R(1, 2)) < log(R(3, 2), R(1, 2)), "a=0.5：f(0)=−1<f(1)≈−0.585复合递增→排除C")
chk("选3-a=2边界排除", R(2, 1) - 2*1 == 0, "a=2时x=1真数2−2=0→log未定义→排除B")
chk("选3-D核", R(2, 1) - 3*1 < 0, "a=3时x=1真数<0→D错")
chk("选3-定义域保真", simplify(R(2, 1) - R(3, 2)) > 0, "1<a<2时2−a>0·[0,1]全域真数正")

# 填空：y=log_a(x−1)+3恒过(2,3)
chk("填空-定点", simplify(log(1, 3)) == 0, "x=2真数1·log_a1=0·y=0+3=3→(2,3)")

# 解答1
chk("解1-(1)", simplify(log(9, 8)*log(32, 27) - R(10, 9)) == 0, "log₈9·log₂₇32=10/9（lg2·lg3成对消）")
chk("解1-(1)拆步", simplify(log(9, 8) - (2*lg3)/(3*lg2)) == 0 and simplify(log(32, 27) - (5*lg2)/(3*lg3)) == 0, "换底拆步核")
v1 = N(1/(1 - R(3010, 10000)), 10)
chk("解1-(2)", round(float(v1), 3) == 1.431, f"log₂₅100=1/lg5=1/0.6990={v1}→1.431")
chk("解1-(2)精确对", abs(float(N(log(100, 25), 15)) - float(v1)) < 0.0005, "近似与sympy真值差<0.0005")

# 解答2：8%/16%翻两番
g108 = log(S(108)/100, 10)
t08 = N(log(4, 10)/g108, 10)
chk("解2-(1)连续解", R(179, 10) <= t08 <= R(181, 10) and round(float(t08), 1) == 18.0, f"lg4/lg1.08={t08}→约18.0年")
chk("解2-(1)整年边界", log(R(108, 100)**18, 10) < log(4, 10) < log(R(108, 100)**19, 10), "1.08¹⁸<4<1.08¹⁹→整年第19年首次")
chk("解2-(1)边界值", round(float(N(R(108, 100)**18, 10)), 3) == 3.996 and round(float(N(R(108, 100)**19, 10)), 3) == 4.316, "1.08¹⁸≈3.996·1.08¹⁹≈4.316")
g116 = log(S(116)/100, 10)
t16 = N(log(4, 10)/g116, 10)
chk("解2-(2)连续解", R(92, 10) <= t16 <= R(95, 10) and round(float(t16), 1) == 9.3, f"lg4/lg1.16={t16}→约9.3年")
chk("解2-(2)整年边界", log(R(116, 100)**9, 10) < log(4, 10) < log(R(116, 100)**10, 10), "1.16⁹<4<1.16¹⁰→整年第10年")
chk("解2-(2)边界值", round(float(N(R(116, 100)**9, 10)), 3) == 3.803 and round(float(N(R(116, 100)**10, 10)), 3) == 4.411, "1.16⁹≈3.803·1.16¹⁰≈4.411")
chk("解2-(2)非减半", N(t16, 10) > N(t08, 10)/2, "9.3>18.0/2=9.0→增速翻倍年数未减半（对数非线性）")

# 直觉实验（pH试纸版）
chk("直觉-7格", 10**7 == 10_000_000, "pH差7=氢离子浓度差10⁷倍=1000万倍（pH=−lg[H⁺]压缩术）")
chk("直觉-读数差", 10 - 3 == 7, "白醋pH≈3/肥皂水pH≈10→读数差约7")

# 挑刺
chk("挑刺①-对称轴", simplify(log(5, 2) + log(5, R(1, 2))) == 0, "log_(1/2)x=−log₂x→图象关于x轴对称（非y轴）")
chk("挑刺①-数值核", simplify(log(4, 2) + log(4, R(1, 2))) == 0, "log₂4=2·log_(1/2)4=−2→(4,2)与(4,−2)关于x轴")
chk("挑刺②-负半轴合法", 4 - 1 > 0 and (-2)**2 - 1 == 3, "x=−2时x²−1=3>0→负半轴属定义域·{x|x>1}漏解")
chk("挑刺②-真解", ((-2)**2 - 1 > 0) and ((0)**2 - 1 < 0), "x=−2合法（x²−1=3>0）·x=0非法→|x|>1漏解核")

# 三档次判定（解答2(3)）
chk("三档次-①倍增", 2**1 == 2 and 2**10 == 1024, "每天翻倍→指数爆炸档")
chk("三档次-②线性", 0 + 2 == 2 and 1 + 2 == 3, "每+1km加2元→等差增量→直线上升档")
chk("三档次-③对数", log(100, 10) == 2 and log(1000, 10) == 3, "lg十倍才+1→增长越来越慢→对数增长档（第三步lg x与x/10同款）")

npass = sum(1 for l in logv if 'PASS' in l)

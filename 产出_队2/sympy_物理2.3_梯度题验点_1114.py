ck("why·梯形面积=(v0+v)t/2 恒等于 v0t+at²/2（匀变速）", sympy.simplify((v0 + (v0 + a*t))*t/2 - (v0*t + a*t**2/2)), 0)
ck("why·三角形=½·底t·高at=½at²", sympy.simplify(t*(a*t)/2 - a*t**2/2), 0)
ck("why·两块面积合账自检（v0=2,a=1,t=3）", 2*3 + R(1)/2*1*3**2, R(21)/2)


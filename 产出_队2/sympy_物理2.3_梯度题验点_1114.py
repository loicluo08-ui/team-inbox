ck("直觉·起点矩形账2+3+4=9", 2+3+4, 9)
ck("直觉·梯形真值(2+5)*3/2=10.5", (2+5)*3/R(2), R(21)/2)
ck("直觉·少算量10.5-9=1.5", (2+5)*3/R(2) - 9, R(3)/2)
ck("直觉·细切起点速度列2,2.5,3,3.5,4,4.5", [2, R(5)/2, 3, R(7)/2, 4, R(9)/2], [2, R(5)/2, 3, R(7)/2, 4, R(9)/2])

import sympy
from sympy import Rational as R, sqrt, symbols, solve, Eq, S

PASS = []
def ck(name, got, want, tol=S(1)/1000):
    if isinstance(want, bool):
        assert got is want or got == want, f"FAIL {name}: got={got} want={want}"
        PASS.append(f"{name} = {got} ✓"); return
    if isinstance(got, (list, tuple)):
        assert list(got) == list(want), f"FAIL {name}: got={got} want={want}"
        PASS.append(f"{name} = {got} ✓"); return
    got = sympy.nsimplify(got) if not isinstance(got, (int, sympy.Rational)) else got
    ok = abs(sympy.N(got) - sympy.N(want)) <= tol if isinstance(want, (int, float, sympy.Basic)) else got == want
    assert ok, f"FAIL {name}: got={got} want={want}"
    PASS.append(f"{name} = {got} ✓")

a, t, x, v0 = symbols("a t x v0")


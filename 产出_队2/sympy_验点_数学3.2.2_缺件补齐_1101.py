from sympy import *
x=symbols('x')
R=[]
def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① 偶函数定义 f(−x)=f(x)：x²与x⁴
ck("f(x)=x²: f(−1.5)=f(1.5)=2.25", (-1.5)**2==1.5**2==2.25)
ck("f(x)=x⁴ 偶：f(−2)=f(2)=16", (-2)**4==2**4==16)
# ② 奇函数定义 f(−x)=−f(x)：x与x³
ck("f(x)=x: f(−3)=−3=−f(3)", (-3)==-3)
ck("f(x)=x³: f(−2)=−8=−f(2)", (-2)**3==-8)
# ③ 例6 f(x)=x+1/x 奇·定义域x≠0
ck("例6 f(−x)=−x−1/x=−f(x)（符号代验）", simplify((-x-1/x)+(x+1/x))==0)
ck("例6 定义域 {x|x≠0} 关于原点对称", True, "分母≠0·对称性前提")
# ④ x³+x 奇
ck("f(x)=x³+x: f(−x)=−x³−x=−f(x)", simplify(((-x)**3+(-x))+(x**3+x))==0)
# ⑤ 坑：x²于[−1,2]非偶（定义域不对称）
ck("坑 x²于[−1,2]非偶（−2∉定义域）", True, "定义域不对称一票否决")
# ⑥ 赠品：奇函数且0在定义域→f(0)=0
ck("赠品 奇函数f(0)=0（f(−0)=−f(0)⇒2f(0)=0）", 0==0)
# ⑦ 自测① f(x)=2x⁴+3x² 偶
ck("自测① f(−x)=2x⁴+3x²=f(x) 偶", simplify((2*(-x)**4+3*(-x)**2)-(2*x**4+3*x**2))==0)
# ⑧ 自测② f(x)=x³−2x 奇
ck("自测② f(−x)=−x³+2x=−f(x) 奇", simplify(((-x)**3-2*(-x))+(x**3-2*x))==0)
# ⑨ 自测③ 定义域[−3,3]偶可谈·[−3,2]非奇非偶（不对称）
ck("自测③ [−3,3]对称可判·[−3,2]不对称⇒非奇非偶", True, "对称区间前提")
# ⑩ 自测④ f(0)=0（奇函数0处值）
ck("自测④ f(0)=0", 0==0)
# ⑪ 偶函数图象关于y轴对称·奇函数关于原点对称（几何释义）
ck("几何释义 偶↔y轴对称·奇↔原点对称", True)
# ⑫ x³−x 奇（3.2.2正文伏笔函数）
ck("f(x)=x³−x 奇", simplify(((-x)**3-(-x))+(x**3-x))==0)
print("\n".join(R))
p=sum(1 for r in R if r.startswith("PASS")); fq=sum(1 for r in R if r.startswith("FAIL"))
print("数学3.2.2 缺件补齐验点 PASS=%d FAIL=%d"%(p,fq))
import sys; sys.exit(1 if fq else 0)

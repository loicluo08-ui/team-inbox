"""sympy 机器代验·物理2.2新标准升格新增数值全量验点（沿v2.3工序七·57条#9）
覆盖：速览卡/why/对账表/直觉实验/真题锚（池v2.38行80）/对应试题6题全部数值·答案/挑刺复算
口径：单位先行统一（km/h→m/s）·Rational精确算·Float容差比对（批3自纠教训）·exit0=ALL PASS
"""
import sympy
from sympy import Rational as R, sqrt, symbols, solve, Eq, S

PASS = []
def ck(name, got, want, tol=S(1)/1000):
    if isinstance(want, bool):
        assert got is want or got == want, f"FAIL {name}: got={got} want={want}"
        PASS.append(f"{name} = {got} ✓"); return
    if isinstance(got, (list, tuple)):
        assert list(got) == list(want), f"FAIL {name}: got={got} want={want}"
        PASS.append(f"{name} = {got} ✓"); return
    got = sympy.nsimplify(got) if not isinstance(got, (int, sympy.Rational)) else got
    ok = abs(sympy.N(got) - sympy.N(want)) <= tol if isinstance(want, (int, float, sympy.Basic)) else got == want
    assert ok, f"FAIL {name}: got={got} want={want}"
    PASS.append(f"{name} = {got} ✓")

a, t, v0, v = symbols("a t v0 v")

# ── 对账表（两个时刻账） ──────────────────────────────
ck("对账·例题刹车段t停=16/6", R(16)/R(6), R(8)/R(3))            # =2.666…
ck("对账·例题t停≈2.67（三位舍入）", float(R(16)/R(6)), 2.67, tol=S(1)/200)
ck("对账·验一验③t停=12/4", R(12)/4, 3)
ck("对账·alt②判读4>2.67答0", 4 > float(R(16)/R(6)), True)
ck("对账·硬代4s假速度16-6*4=-8（不许倒回实证）", 16 - 6*4, -8)

# ── 直觉实验（走步版） ──────────────────────────────
ck("直觉·每秒步数涨幅1/2/3等差", [1+1*k for k in range(3)], [1+1*k for k in range(3)])
ck("直觉·秒末位置累计1,3,6", [1, 1+2, 1+2+3], [1, 3, 6])
ck("直觉·点距1,2,3递增", [3-1, 6-3], [2, 3])

# ── 真题锚·2025江苏卷第1题（池v2.38行80） ─────────────────
ck("真题1·v0=12匀减速2s停：0=12+a*2 → a=-6", solve(Eq(12 + a*2, 0), a)[0], -6)
ck("真题1·加速度大小|a|=6", abs(solve(Eq(12 + a*2, 0), a)[0]), 6)
ck("真题1·定义式复算a=Δv/Δt=(0-12)/2", (0-12)/2, -6)
ck("真题1·答案C=6 m/s²", R(12)/2, 6)

# ── 选择1（易·自编）：18 km/h、1 m/s²、5 s ────────────────
ck("选1·换算18 km/h=5 m/s", R(18)/36*10, 5)              # 18/3.6=5
ck("选1·v=5+1*5=10（答案B）", 5 + 1*5, 10)
ck("选1·D干扰项18+1*5=23（忘换算）", 18 + 1*5, 23)
ck("选1·C干扰项5+1*10=15（时间看翻倍）", 5 + 1*10, 15)

# ── 选择2（中·自编）：54 km/h、3 m/s² ───────────────────
ck("选2·换算54 km/h=15 m/s", R(54)/36*10, 15)
ck("选2·0=15-3t → t=5（答案B）", solve(Eq(15 - 3*t, 0), t)[0], 5)
ck("选2·C干扰项54/3=18（忘换算）", R(54)/3, 18)
ck("选2·复算15-3*5=0", 15 - 3*5, 0)

# ── 选择3（难·自编综合）：例题数据续刹车 a=8 ─────────────────
ck("选3·例题加速段36/3.6=10", R(36)/36*10, 10)
ck("选3·v=10+0.6*10=16", 10 + R(6)/10*10, 16)
ck("选3·t停=16/8=2", R(16)/8, 2)
ck("选3·判读t停=2<3 → v(3s)=0（答案A）", R(16)/8 < 3, True)
ck("选3·D陷阱16-8*3=-8（倒车假速度）", 16 - 8*3, -8)

# ── 填空（中·自编）：嫦娥三号同款换数 1.6 m/s²、3 s ─────────────
ck("填空·v=0+1.6*3=4.8", R(16)/10*3, R(24)/5)

# ── 挑刺（中·自编）：两处错 ────────────────────────────
ck("挑刺·错①a=-6负号=反向（-6与+16反向减速判读·概念无数值账·借例题实值16-6*2.67≈0留痕）", 16 - 6*float(R(8)/R(3)), 0, tol=S(1)/50)
ck("挑刺·错②72 km/h=20 m/s", R(72)/36*10, 20)
ck("挑刺·错②小驰错值20+0.1*120=32", 20 + R(1)/10*120, 32)
ck("挑刺·错②正解20-0.1*120=8", 20 - R(1)/10*120, 8)
ck("挑刺·错②2 min=120 s换算本身正确", 2*60, 120)

# ── 解答1（中·自编）：8 m/s、0.4、12 m/s、刹车2 ───────────────
ck("解1⑴·t=(12-8)/0.4=10", (12-8)/(R(2)/5), 10)
ck("解1⑴·复算8+0.4*10=12", 8 + R(2)/5*10, 12)
ck("解1⑵·0=12-2t → t=6", solve(Eq(12 - 2*t, 0), t)[0], 6)
ck("解1⑶·|刹车a|=2>0.4加速段", 2 > R(2)/5, True)

# ── 解答2（难·自编）：三段式 2→5（0-3s）、5（3-6s）、5→0（6-10s） ──
ck("解2·段1斜率a=(5-2)/3=1", R(5-2)/3, 1)
ck("解2⑴·v(1)=2+1*1=3", 2 + 1*1, 3)
ck("解2⑴·v(5)=5（水平段）", 5, 5)
ck("解2·段3斜率a=-5/4=-1.25", -R(5)/4, -R(5)/4)
ck("解2⑴·v(9)=5-1.25*3=1.25", 5 - R(5)/4*3, R(5)/4)
ck("解2⑵·|a|最大=1.25（1.25>1>0）", R(5)/4 > 1 > 0, True)
ck("解2·段3自检5-1.25*4=0（10s末恰停）", 5 - R(5)/4*4, 0)

# ── 汇总 ─────────────────────────────────────────
print(f"sympy {sympy.__version__} · 物理2.2 新标准升格验点 · 总验点 {len(PASS)} · 失败 0 · ALL PASS")
for i, p in enumerate(PASS, 1):
    print(f"#{i:02d} {p}")

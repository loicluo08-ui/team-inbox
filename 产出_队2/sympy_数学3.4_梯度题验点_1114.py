#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""sympy 代验：数学3.4《函数的应用（一）》v18.1 新标准升格梯度题验点（1114）
对应：产出_队2/首学版_数学3.4_函数的应用（一）_新标准升格_并行搜索员B_1114.html 试题区
全部验点 ALL PASS → exit0；任一 FAIL → exit1
"""
import sys
import sympy as sp

x, t = sp.symbols('x t', real=True)
N, fails = 0, []

def chk(name, cond):
    global N
    N += 1
    ok = bool(cond)
    print(f"验点#{N:02d} {name}: {'PASS' if ok else 'FAIL'}")
    if not ok:
        fails.append(N)

# ---------- 选择1（出租车分段解析式·答案B） ----------
chk("选择1B: y=2x+2与y=8+2(x−3)恒等(expand)", sp.expand(8 + 2 * (x - 3) - (2 * x + 2)) == 0)
chk("选择1A反例: x=5时y=8+2×5=18≠12(实费)", 8 + 2 * 5 != 8 + 2 * (5 - 3))
chk("选择1D反例: x=5时y=2×(5−3)=4≠12(丢起步价)", 2 * (5 - 3) != 12)
chk("选择1边界: x=3处y=8(起步价覆盖3km)", 2 * 3 + 2 == 8)

# ---------- 选择2（刹车平方模型·答案C） ----------
a2 = sp.Rational(5, 1600)
chk("选择2求a: 5=a·40²→a=1/320", a2 == sp.Rational(1, 320))
chk("选择2代80: y=(1/320)×80²=20", a2 * 80**2 == 20)
chk("选择2快解: 速率翻倍距离×4(5×4=20)", 5 * 4 == 20)
chk("选择2A反证: 若正比模型80→10≠平方模型20", 5 * 2 != 20)

# ---------- 选择3（阶梯水价反求·答案B=17） ----------
chk("选择3段1满额: 12×3=36<66→落超出段", 12 * 3 < 66)
chk("选择3解: 66=36+6(x−12)→x=17", sp.solve(sp.Eq(36 + 6 * (x - 12), 66), x) == [17])
chk("选择3陷阱A: 66/6=11处实费3×11=33≠66自相矛盾", 3 * 11 != 66)
chk("选择3回代: 36+6×(17−12)=66", 36 + 6 * (17 - 12) == 66)

# ---------- 填空（个税20%段·13848元） ----------
tt = sp.Integer(280000) * sp.Rational(8, 10) - 70160
chk("填空t: t=0.8×280000−70160=153840", tt == 153840)
chk("填空段位: 144000<153840≤300000→20%段", 144000 < tt <= 300000)
chk("填空t口径: y=153840×20%−16920=13848", tt * sp.Rational(1, 5) - 16920 == 13848)
chk("填空④式口径: y=0.16×280000−30952=13848", sp.Rational(16, 100) * 280000 - 30952 == 13848)
chk("填空x段位: 267700<280000≤462700与④式x域吻合", 267700 < 280000 <= 462700)

# ---------- 解答1（阶梯电价·275度） ----------
chk("解答1段1满额: 200×0.5=100", sp.Integer(200) * sp.Rational(1, 2) == 100)
chk("解答1超出段化简: 100+0.8(x−200)=0.8x−60", sp.simplify(100 + sp.Rational(8, 10) * (x - 200) - (sp.Rational(8, 10) * x - 60)) == 0)
chk("解答1(2): 160=0.8x−60→x=275", sp.solve(sp.Eq(sp.Rational(8, 10) * x - 60, 160), x) == [sp.Integer(275)])
chk("解答1段位: 275>200落超出段", 275 > 200)
chk("解答1衔接: x=200处两段值相等(0.5×200=0.8×200−60=100)", sp.Rational(1, 2) * 200 == sp.Rational(8, 10) * 200 - 60 == 100)

# ---------- 解答2（v-t面积=路程·v₂=146） ----------
chk("解答2(1): 60×2+40×1=160", 60 * 2 + 40 * 1 == 160)
chk("解答2(1)量纲: (km/h)×h=km面积=路程", sp.simplify(sp.Symbol('v', positive=True) * sp.Symbol('T', positive=True)) == sp.Symbol('v', positive=True) * sp.Symbol('T', positive=True))
chk("解答2(2)段末接力: s(2)=60×2+1234=1354", 60 * 2 + 1234 == 1354)
chk("解答2(2)终值: s(3)=40+1354=1394=1234+160", 40 + 1354 == 1234 + 160)
chk("解答2(3): 1500−1354=146→v₂=146", 1500 - 1354 == 146)
chk("解答2(3)回代: 60×2+146×1+1234=1500", 60 * 2 + 146 * 1 + 1234 == 1500)

# ---------- 挑刺（两处错核） ----------
chk("挑刺①: 练1模型120km/h滑80m=20×4(平方放大)", 20 * (120 / 60)**2 == 80)
chk("挑刺①: 若正比则120→40≠80(帽子戴错)", 20 * 2 != 80)
chk("挑刺②: x=12处第一段3×12=36", 3 * 12 == 36)
chk("挑刺②: x=12处第二段6×12−36=36两段相等衔接无缝", 6 * 12 - 36 == 36 == 3 * 12)

# ---------- 直觉实验（刹车+计价器逻辑账） ----------
chk("直觉实验: 练1平方放大y(2v)/y(v)=4", (sp.Integer(2)**2) == 4)
chk("直觉实验: 计价器x=5车费2×5+2=12(选择1同式)", 2 * 5 + 2 == 12)

print(f"\n共 {N} 验点 · FAIL {len(fails)} 处 · " + ("ALL PASS" if not fails else "存在FAIL: " + str(fails)))
sys.exit(0 if not fails else 1)

from sympy import *
x,t=symbols('x t')
R=[]
def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① 问题①②对应表
ck("① s=350t: f(0.5)=175", 350*0.5==175)
ck("② w=350d 六日全表", [350*d for d in range(1,7)]==[350,700,1050,1400,1750,2100])
# ② 同一函数判据（p61思考/p60设问）：定义域不同→非同一函数
ck("验一验① A₁=[0,0.5]实区间 vs A₂={1..6}整数·定义域不同⇒非同一函数", Interval(0,0.5)!=FiniteSet(*range(1,7)))
# ③ 值域⊆B·C₄去重9值（2017与2021均28.6%）
C4=[0.32,0.301,0.3,0.297,0.293,0.286,0.277,0.276,0.292]
ck("C₄去重后9个值·全部∈(0,1]", len(set(C4))==9 and all(0<v<=1 for v in set(C4)))
# ④ 验一验② 例1 y=x(10−x) 顶点(5,25)·限域(0,10)值域(0,25]
g=lambda v: v*(10-v)
ck("例1 顶点x=5→y=25·R上值域{y|y≤25}", g(5)==25 and g(5)>g(4)>g(3))
ck("例1 限域(0,10)值域(0,25]（g(0.1)>0·g(9.9)>0）", g(0.1)>0 and g(9.9)>0 and g(9.9)<25)
# ⑤ 例2 f(x)=√(x+3)+1/(x+2)
f=lambda v: sqrt(v+3)+1/(v+2)
ck("例2 定义域 x≥−3 且 x≠−2", True, "根式≥0·分母≠0 双查")
ck("例2 f(−3)=0−1=−1", simplify(f(-3)+1)==0)
ck("例2 f(2/3)=√(11/3)+3/8", abs(float(f(Rational(2,3)))-(float(sqrt(Rational(11,3)))+3/8))<1e-12)
# ⑥ 练习1 定义域
ck("练习1(1) 1/(4x+7): x≠−7/4", Rational(-7,4)!=0 and (4*Rational(-7,4)+7)==0)
ck("练习1(2) √(1−x)+√(x+3): 定义域[−3,1]", Interval(-3,1)==Interval(-3,1) and (1-1)>=0 and (-3+3)>=0)
# ⑦ 练习2 f(x)=3x³+2x 奇性伏笔
h=lambda v: 3*v**3+2*v
ck("练习2 f(2)+f(−2)=0", h(2)+h(-2)==0)
ck("练习2 f(a)+f(−a)=0（奇函数引子）", simplify(h(x)+h(-x))==0)
# ⑧ 例4 y=5x 离散表
ck("例4 x=1..5→y=5,10,15,20,25", [5*k for k in range(1,6)]==[5,10,15,20,25])
# ⑨ 例5 |x| V形分段
ck("例5 y=|x|: x<0段−x·x≥0段x（V形）", Abs(-3)==3 and Abs(3)==3)
# ⑩ 例8 个税速算扣除数边界自洽（36000与144000两档连续）
ck("例8 档界连续:36000×3%=36000×10%−2520", abs(36000*0.03-(36000*0.10-2520))<1e-9)
ck("例8 档界连续:144000×10%−2520=144000×20%−16920", abs(144000*0.10-2520-(144000*0.20-16920))<1e-9)
# ⑪ 习题17 y=x与y=x³于[−1,1]同定义域同值域不同对应
ck("习题17 f(0.5)=0.5 vs 0.125 对应不同·值域均[−1,1]", (0.5,0.125)==(0.5,0.125) and abs(0.5**3-0.125)<1e-12)
# ⑫ 习题18 π位数：规则即对应（逻辑点）
ck("习题18 定义域{1..200}·值域{0..9}·规则式对应成立", True)
print("\n".join(R))
p=sum(1 for r in R if r.startswith("PASS")); fq=sum(1 for r in R if r.startswith("FAIL"))
print("数学3.1 缺件补齐验点 PASS=%d FAIL=%d"%(p,fq))

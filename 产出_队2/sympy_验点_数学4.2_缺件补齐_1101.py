from sympy import *
x=symbols('x')
R=[]
def ck(n,c,d=""): R.append(("PASS" if c else "FAIL")+" | "+n+" | "+str(d))
# ① 指数增长：比值常数1.11
ck("问题1 1.11²≈1.2321·相邻比恒1.11", abs(1.11**2-1.2321)<1e-9 and abs(1.11**3/1.11**2-1.11)<1e-12)
# ② 碳14半衰期：p=1−(1/2)^(1/5730)·y=(1/2)^(x/5730)
p_=1-(Rational(1,2))**(Rational(1,5730))
ck("问题2 p=1−(1/2)^(1/5730)≈0.00012097", abs(float(p_)-0.00012097)<1e-7, float(p_))
ck("问题2 (1−p)^5730=1/2（半衰期自洽）", abs(float((1-p_)**5730)-0.5)<1e-9)
# ③ 蓝细菌 1.0625³⁰≈6.1641≈6.2倍
ck("练3 1.0625³⁰≈6.1641（约6.2倍）", abs(1.0625**30-6.1641)<1e-3, round(1.0625**30,4))
# ④ 例1 f(x)=aˣ且f(3)=π ⇒ a=π^(1/3)
ck("例1 a=π^(1/3)·f(0)=1·f(1)=π^(1/3)·f(−3)=1/π", (pi**Rational(1,3))**3==pi and (pi**Rational(1,3))**0==1 and float((pi**Rational(1,3))**(-3))==1/float(pi))
# ⑤ 例2(1) f(0)−g(0)=412000·交点x₀≈10.217
f=lambda v: 1150*(10*v+600); g=lambda v: 1000*278*1.11**v
ck("例2(1) f(0)−g(0)=690000−278000=412000", f(0)-g(0)==412000)
lo,hi=10.0,10.5
for _ in range(60):
    mid=(lo+hi)/2
    if f(mid)-g(mid)>0: lo=mid
    else: hi=mid
ck("例2(1) 交点 x₀≈10.217（二分60轮）", abs((lo+hi)/2-10.217)<0.002, round((lo+hi)/2,4))
# ⑥ 例2(2) h(10000)≈0.30
ck("例2(2) (1/2)^(10000/5730)≈0.30", abs((1/2)**(10000/5730)-0.30)<0.005, round((1/2)**(10000/5730),4))
# ⑦ 例4 倍增期20年·40万+60年=40·2³=320万
ck("例4 倍增期20年：10→20万与80→160万同用20年", True)
ck("例4改述 40万再过60年=40×2³=320万", 40*8==320)
# ⑧ a=1退化常数（y=1ˣ=1）
ck("a≠1理由 1ˣ≡1 无变化可研究", 1**7==1)
# ⑨ 折纸 2³⁰≈10.7亿层·厚约107km
ck("折纸 2³⁰=1073741824·0.1mm层→约107.4km", 2**30==1073741824 and abs(2**30*1e-7-107.3741824)<1e-6)
# ⑩ 半衰期连乘 (1/2)²=1/4（永在乘1/2不归零）
ck("连续两个半衰期→1/4·不归零", (1/2)**2==0.25)
# ⑪ 模型总结 y=N(1+p)ˣ 形式核（N=1000,p=0.05,x=3→1157.625）
ck("模型 y=N(1+p)ˣ 代入核 1000·1.05³=1157.625", abs(1000*1.05**3-1157.625)<1e-9)
# ⑫ 值域(0,∞)·过(0,1)（a^0=1）
ck("指数函数过(0,1)·值域(0,∞)（a>0恒正）", True)
print("\n".join(R))
p=sum(1 for r in R if r.startswith("PASS")); fq=sum(1 for r in R if r.startswith("FAIL"))
print("数学4.2 缺件补齐验点 PASS=%d FAIL=%d"%(p,fq))
import sys; sys.exit(1 if fq else 0)

# 地理1.1 新标准增补件 数值验点（队2席·搜索规划师·1114）
# 覆盖：填空题（太阳光到地球500秒/8.3分钟）+ 正本既有活动数值复核（光年换算口径）
from sympy import Rational, nsimplify
ok = []
# 1) 填空题：时间 = 路程 ÷ 速度
t = Rational(15,10)*10**8 / (Rational(3)*10**5)     # 1.5e8 km ÷ 3e5 km/s
assert t == 500, t
ok.append(f"1) 1.5×10⁸ km ÷ 3×10⁵ km/s = {t} 秒 （题面答案=500秒 ✓）")
# 2) 折合分钟（保留一位小数）
m = Rational(500, 60)
assert float(m) >= 8.3 and float(m) < 8.35, float(m)
ok.append(f"2) 500 ÷ 60 = {float(m):.4f} 分钟 → 保留一位小数 = 8.3 分钟 ✓")
# 3) 正本try②同口径复核（500秒≈8.3分钟 一致性）
assert Rational(150000000, 300000) == 500
ok.append("3) 正本试试看②同数据一致性复核 = 500秒 ✓")
# 4) 光年换算口径复核（正本附表口径：3×10⁵ km/s × 365.25天）
ly = Rational(3)*10**5 * Rational(36525,100) * 86400
ok.append(f"4) 1光年按365.25天复算 = {float(ly):.3e} 千米（正本记9.4673×10¹²口径 ✓ 不涉新增题）")
# 5) 选择3概念核：260万光年=距离 → 光走260万年（定义推演，无数值运算）——标注仅逻辑核
ok.append("5) 选择3：260万光年→光行约260万年 = 光年定义（距离单位）直接推演，无算术运算（逻辑核✓）")
print("\n".join(ok))
print("EXIT=0 · 全部验点通过")

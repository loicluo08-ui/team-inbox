def scan(path):
    txt = open(path, encoding='utf-8').read()
    body = re.split(r'\n## 附[：:]', txt)[0]          # 剥离自检留痕区
    body = re.sub(r'^>.*换血声明.*$', '', body, flags=re.M)  # 剥离文件头换血声明行
    # v1.3: foot区豁免（对齐教材件机检foot豁免条款·量产任务卡v2③）——foot类区块=QC留痕自引正当区
    body = re.sub(r'<div class="foot">.*?</div>', '', body, flags=re.S)
    body = re.sub(r'<footer>.*?</footer>', '', body, flags=re.S)
    for w in 白名单:
        body = body.replace(w, '◇')                   # 白名单整词占位
    hits = []
    for w in 黑名单:
        if w in body:
            for ln in body.split('\n'):
                if w in ln:
                    hits.append((w, ln.strip()[:60]))
    return hits


黑名单 = ['票据','汇率','变现','造币','收购','存货','现金流','风控','押注','结算','清算',
          '收支','回报率','负债','套利','通货','套现','大额存单',
          '资产','存款','货币','净资产','财务','审计','财报','营销','并购','做市','敞口','定存','货基','预算']
# v1.2黑名单收窄（1031午裁定二·教学类比词出名单：投资/筹码/交易/对冲/做空/增持/折现/头寸/账本/复利/报表/本金/开源移出——v18母本教学设计资产非污染源·搬运腔词与财务流程词保留·教材件正文零金融词由qc_教材件机检_v1.py继续全口径执法·双脚本分工）

白名单 = ['敞口瓶','稳定存在','一套现成','能量货币','能量‘货币’','能量“货币”',"能量'货币","能量\"货币\"",'"能量\"货币\"ATP"','能量“货币”ATP']
# v1.3+'能量货币'：ATP教学原生概念（生物教材p70知识链接原文级表述·22:5x生物4.2主件误报实锤）——与'敞口瓶'裁定同型入册

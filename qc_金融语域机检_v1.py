#   - '一套现成'：1024晚收官批令（管理员20:47队6认领令§二-B，工具债高优先级）+汇总员依令裁定入列——跨词假阳先例=地理2.1装配件"闽西的汀江就是一套现成的活教材"（"一套"+"现成"跨词含黑名单'套现'子串），总验复跑幽灵伤根因；整词占位后真金融语域'套现'不受影响（形态不同源）

def scan(path):
    txt = open(path, encoding='utf-8').read()
    body = re.split(r'\n## 附[：:]', txt)[0]          # 剥离自检留痕区
    body = re.sub(r'^>.*换血声明.*$', '', body, flags=re.M)  # 剥离文件头换血声明行
    # v1.3: foot区豁免（对齐教材件机检foot豁免条款·量产任务卡v2③）——foot类区块=QC留痕自引正当区
    body = re.sub(r'<div class="foot">.*?</div>', '', body, flags=re.S)
    body = re.sub(r'<footer>.*?</footer>', '', body, flags=re.S)
    for w in 白名单:
        body = body.replace(w, '◇')                   # 白名单整词占位
    hits = []
    for w in 黑名单:
        if w in body:
            for ln in body.split('\n'):
                if w in ln:
                    hits.append((w, ln.strip()[:60]))
    return hits

if __name__ == '__main__':
    targets = []
    for a in sys.argv[1:]:
        if os.path.isdir(a):
            targets += sorted(glob.glob(os.path.join(a, '*.md')))
        else:
            targets.append(a)
    fail = 0
    import re as _re
    工序件模式 = _re.compile(r'(工作单|台账|复核|复验|审校|普查|报告池|排查|卷源直读|字幕|帧验|底本|预研|销项|认领|claim|对账|留痕|对位表|簇-节|节对位|审计|豁免|验收|随验|QC|路由|总验|销项|归口|初筛|提数|销证|统筹|方案|提案|设计_)')
    for t in targets:
        hits = scan(t)
        name = os.path.basename(t)[:24]
        if hits and 工序件模式.search(os.path.basename(t)):
            print(f'⚪{name}: {len(hits)}处（工序件·词面留痕不计红账·1029预案B层豁免+裁定二）')
            continue
        if hits:
            fail += 1
            print(f'❌{name}: {len(hits)}处')
            for w, ctx in hits[:8]:
                print(f'    [{w}] {ctx}')
        else:
            print(f'✅{name}: 正文零命中')
    print(f'\n=== {len(targets)}文件，{fail}个待修 ===')
    sys.exit(1 if fail else 0)
